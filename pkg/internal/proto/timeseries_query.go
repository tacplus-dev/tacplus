// tsQueryProjection represents a single timeseries_type message that should be
// exposed as a typed, paged List RPC in the TimeseriesQuery service.
//
// A timeseries query is a FEDERATION index, not a data source: it returns the
// SOURCE RECORD KEYS of rows matching a time range (carried by the row's
// projection_record_key field), and the record store hydrates the full immutable records
// from the record_store. The grouped-analytics plane (TimeseriesGroupCounts) and
// raw ExecuteQuery are unaffected.
type tsQueryProjection struct {
	typeName string // timeseries_type/table message name, e.g. "SessionRecord"
	orderBy  string // stable-paging key — the record key field name
	keyType  string // proto type of the record key field, e.g. "string" (return type)
}

// AppendTimeseriesQueryServiceToProtos scans all proto files for spec.timeseries_type
// messages and appends a TimeseriesQuery service — a per-projection paged query that
// returns SOURCE RECORD KEYS within a time range — to the proto of every
// timeseries_store (timedb).
//
// Like its sibling injectors (AppendRecordMapServiceToProtos) this runs on EVERY
// service's codegen so the injected service is visible in every proto view (e.g.
// argus declares a grpc_s2s_client against timedb.TimeseriesQuery); the injection
// is identical regardless of who is building, so selfPackage is unused. It parses
// tempProtoDir so it sees the
// projection messages (with their injected record-key field) generated by
// GenerateProjectionMessages in the previous step.
func AppendTimeseriesQueryServiceToProtos(tempProtoDir, inputDir, selfPackage string) error {
	_ = selfPackage
	dp, err := parser.NewDescriptorParser(tempProtoDir)
	if err != nil {
		return fmt.Errorf("failed to create descriptor parser for timeseries query injection: %w", err)
	}

	// Find every timeseries_store service proto (independent of who is building).
	// Like TimeseriesGroupCounts, this is the store's OWN service.
	var serviceRelPaths []string
	for relPath, fd := range dp.GetAllFiles() {
		if fd.ServiceName != "" && fd.TimeseriesStore {
			serviceRelPaths = append(serviceRelPaths, relPath)
		}
	}
	if len(serviceRelPaths) == 0 {
		return nil
	}
	sort.Strings(serviceRelPaths)

	// Collect all timeseries_type messages.
	var projections []tsQueryProjection
	for relPath, fd := range dp.GetAllFiles() {
		if IsInfraProto(relPath) {
			continue
		}
		for _, msg := range fd.Messages {
			if _, ok := msg.Annotations["timeseries_type"]; !ok {
				continue
			}
			keyName, keyType, ok := projectionRecordKey(msg)
			if !ok {
				// Every projection carries a record key post-injection; fall back to a
				// string key ordered by the first field for any hand-written type.
				keyName = timeseriesFirstField(msg)
				keyType = "string"
			}
			projections = append(projections, tsQueryProjection{
				typeName: msg.Name,
				orderBy:  keyName,
				keyType:  keyType,
			})
		}
	}
	if len(projections) == 0 {
		return nil
	}
	sort.Slice(projections, func(i, j int) bool {
		return projections[i].typeName < projections[j].typeName
	})

	for _, serviceRelPath := range serviceRelPaths {
		if err := appendTimeseriesQueryToServiceProto(tempProtoDir, serviceRelPath, projections); err != nil {
			return err
		}
	}
	return nil
}

// appendTimeseriesQueryToServiceProto appends the TimeseriesQuery service
// definition and its per-projection messages to one timeseries_store service proto.
func appendTimeseriesQueryToServiceProto(tempProtoDir, relPath string, projections []tsQueryProjection) error {
	filePath := filepath.Join(tempProtoDir, relPath)
	content, err := os.ReadFile(filePath)
	if err != nil {
		return fmt.Errorf("failed to read proto file %s: %w", relPath, err)
	}

	var sb strings.Builder
	sb.WriteString("\n// Auto-generated timeseries key query service from spec.timeseries_type annotations (tacplus)\n")

	for _, p := range projections {
		reqName := "List" + p.typeName + "Request"
		respName := "List" + p.typeName + "Response"
		// The response carries SOURCE RECORD KEYS, not rows: the record store federates into
		// this query, gets the keys, and hydrates the full records from the record_store.
		// TimeRange is defined by the timedb service's own proto (as for GroupCounts).
		sb.WriteString(fmt.Sprintf(`
message %s {
  TimeRange time_range = 1;
  int32 page_size = 2;
  string page_token = 3;
}

message %s {
  repeated %s record_keys = 1;
  string next_page_token = 2;
  int64 total_count = 3;
}
`, reqName, respName, p.keyType))
	}

	// TWO CALLER SURFACES, ONE QUERY PLANE — the same split record_map.go makes
	// for RecordMap/RecordQuery, for the same reason.
	//
	// A service declares exactly one caller surface (parser.ValidateServiceSurfaces
	// refuses a service carrying two), so the plane is emitted TWICE:
	//
	//   TimeseriesQuery     S2S. Reached by a peer service, authorized by peer
	//                       identity through auth_services. Unchanged.
	//   TimeseriesKeyQuery  C2S. Reached with a user token through the gateway,
	//                       authorized by that token's service entitlements.
	//
	// The c2s half is not a convenience alias. registry.collectEntitlementGrants
	// builds the platform's grant catalog from c2s RPCs ONLY, so an s2s-only
	// surface has no grant vocabulary at all: a timeseries store minted zero
	// <PKG>_* grants and no <PKG>_ANY macro, and no grant string — wildcard or
	// exact — could authorize a user call into it. Emitting the c2s sibling is
	// what puts the timeseries query plane INTO the catalog, so <PKG>_ANY becomes
	// a real grant that grows with new projections by generation rather than by
	// hand.
	//
	// Both surfaces share every message above AND every RPC name: List<T> already
	// classifies as LIST/PAGE against the closed verb registry, which is what a
	// c2s RPC must do, so one logical operation carries one name on both.
	//
	// Direction ruling (2026-08-23, restated 2026-08-25): a client calls timedb
	// DIRECTLY with a user token — it does not federate through the record store.
	// That is why the answer here is a c2s twin and NOT widening the s2s
	// auth_services allowlist.
	sb.WriteString(timeseriesQueryS2SService(projections))
	sb.WriteString(timeseriesKeyQueryC2SService(projections))

	var buf strings.Builder
	buf.Write(content)
	buf.WriteString(sb.String())
	if err := os.WriteFile(filePath, []byte(buf.String()), 0644); err != nil {
		return fmt.Errorf("failed to write proto file %s: %w", relPath, err)
	}

	zap.L().Info("appended TimeseriesQuery service",
		zap.String("file", relPath),
		zap.Int("projections", len(projections)))
	return nil
}

// timeseriesQueryS2SService renders the S2S half of the timeseries key query
// plane: the service a peer reaches directly, authorized by peer identity
// through auth_services rather than by a user token's entitlements.
func timeseriesQueryS2SService(projections []tsQueryProjection) string {
	var sb strings.Builder
	sb.WriteString("\nservice TimeseriesQuery {\n")
	sb.WriteString("  option (spec.service_s2s) = {};\n")
	for _, p := range projections {
		reqName := "List" + p.typeName + "Request"
		respName := "List" + p.typeName + "Response"
		sb.WriteString(fmt.Sprintf(`
  rpc List%s(%s) returns (%s) {
    option (spec.rpc) = {principal: RPC_PRINCIPAL_SERVICE, auth_services: ["argus"]};
    option (spec.method_collection) = {mode: COLLECTION_MODE_PAGE, order_by: [%q], default_page_size: 100};
  }
`, p.typeName, reqName, respName, p.orderBy))
	}
	sb.WriteString("}\n")
	return sb.String()
}

// timeseriesKeyQueryC2SService renders the C2S half: the same per-projection
// paged key query, reachable with a user token through the gateway and
// authorized by that token's service entitlements. It carries no (spec.rpc)
// auth override — the service-level auth_entitled_users default is the whole
// point, since that is what puts these RPCs in the generated grant catalog.
// See the surface comment in appendTimeseriesQueryToServiceProto.
func timeseriesKeyQueryC2SService(projections []tsQueryProjection) string {
	var sb strings.Builder
	sb.WriteString("\nservice TimeseriesKeyQuery {\n")
	sb.WriteString("  option (spec.service_c2s) = {auth_entitled_users: true};\n")
	for _, p := range projections {
		reqName := "List" + p.typeName + "Request"
		respName := "List" + p.typeName + "Response"
		sb.WriteString(fmt.Sprintf(`
  rpc List%s(%s) returns (%s) {
    option (spec.method_collection) = {mode: COLLECTION_MODE_PAGE, order_by: [%q], default_page_size: 100};
  }
`, p.typeName, reqName, respName, p.orderBy))
	}
	sb.WriteString("}\n")
	return sb.String()
}

// timeseriesFirstField returns the first field name of a timeseries_type message
// (fallback stable-paging key for a hand-written type with no record key).
func timeseriesFirstField(msg parser.MessageDescriptor) string {
	for _, f := range msg.Fields {
		if f.Name != "" {
			return f.Name
		}
	}
	return "event_id"
}

// projectionRecordKey returns the name and proto type of the projection field
// marked (spec.projection_record_key) — the source record's key, injected by the
// projection generator. This is what a federation query returns for hydration.
func projectionRecordKey(msg parser.MessageDescriptor) (name, protoType string, ok bool) {
	for _, f := range msg.Fields {
		if ann, has := f.Annotations["projection_record_key"]; has && ann.BoolValue {
			return f.Name, f.Type, true
		}
	}
	return "", "", false
}
