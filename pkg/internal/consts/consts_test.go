func TestHeaderLines_NoCopyright(t *testing.T) {
	// The copyright line comes from tacplus.yaml (header.SetCopyright), never from here.
	for _, line := range HeaderLines() {
		if strings.Contains(line, "Copyright") {
			t.Errorf("HeaderLines() must not carry a copyright line, got %q", line)
		}
	}
	if lines := HeaderLines(); lines[0] != "Generated by tacplus" {
		t.Errorf("first line = %q, want generator tag", lines[0])
	}
}

