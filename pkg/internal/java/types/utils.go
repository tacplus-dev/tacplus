	b.WriteString("            }\n")
	b.WriteString("        } catch (IllegalArgumentException ignored) {}\n")
	b.WriteString("        try {\n")
	b.WriteString("            String decoded = new String(Base64.getDecoder().decode(value), java.nio.charset.StandardCharsets.UTF_8);\n")
	b.WriteString("            if (decoded.contains(\"-----BEGIN\") && decoded.contains(\"-----END\")) {\n")
	b.WriteString("                return decoded;\n")
	b.WriteString("            }\n")
	b.WriteString("        } catch (IllegalArgumentException ignored) {}\n")
	b.WriteString("        try {\n")
	b.WriteString("            String decoded = new String(Base64.getUrlDecoder().decode(padBase64(value)), java.nio.charset.StandardCharsets.UTF_8);\n")
