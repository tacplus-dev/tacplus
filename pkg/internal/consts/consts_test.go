func TestHeaderLinesWithSource_EmptySource(t *testing.T) {
	withSrc := HeaderLinesWithSource("")
	base := HeaderLines()

	if len(withSrc) != len(base) {
		t.Errorf("HeaderLinesWithSource(\"\") returned %d lines, want %d (same as HeaderLines)",
			len(withSrc), len(base))
	}

	for i := range base {
		if withSrc[i] != base[i] {
			t.Errorf("line %d differs: got %q, want %q", i, withSrc[i], base[i])
		}
	}
}

func TestHeaderLinesWithSource_NonEmptySource(t *testing.T) {
	source := "foo/bar.proto"
	lines := HeaderLinesWithSource(source)
	base := HeaderLines()

	// Should have 2 extra lines: an empty separator and the source reference.
	expectedLen := len(base) + 2
	if len(lines) != expectedLen {
		t.Fatalf("HeaderLinesWithSource(%q) returned %d lines, want %d",
			source, len(lines), expectedLen)
	}

	// The base portion must be identical.
	for i := range base {
		if lines[i] != base[i] {
			t.Errorf("line %d differs: got %q, want %q", i, lines[i], base[i])
		}
	}

	// Blank separator line.
	if lines[len(base)] != "" {
		t.Errorf("separator line = %q, want empty string", lines[len(base)])
	}

	// Source reference line.
	expected := "Source: " + source
	if lines[len(base)+1] != expected {
		t.Errorf("source line = %q, want %q", lines[len(base)+1], expected)
	}
}

func TestHeaderLinesWithSource_DoesNotMutateHeaderLines(t *testing.T) {
	before := HeaderLines()
	_ = HeaderLinesWithSource("some/source.proto")
	after := HeaderLines()

	if len(before) != len(after) {
		t.Fatal("calling HeaderLinesWithSource mutated HeaderLines result length")
	}
	for i := range before {
		if before[i] != after[i] {
			t.Errorf("HeaderLines line %d changed after HeaderLinesWithSource call: %q -> %q",
				i, before[i], after[i])
		}
	}
}

