package proto

import (
	"fmt"
	"gitlab.com/seabeam/schematic/tacplus/pkg/internal/common/header"
	"gitlab.com/seabeam/schematic/tacplus/pkg/internal/consts"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gitlab.com/seabeam/schematic/tacplus/pkg/internal/common/strutil"
	"go.uber.org/zap"

	"gitlab.com/seabeam/schematic/tacplus/pkg/internal/common/parser"
)

// GeneratePersistedStoreEnum scans every proto file for `service_store`-annotated
// messages and emits `generated/persisted_store.proto` containing a
// `PersistedStore` enum with one value per store
// (`PERSISTED_STORE_<MESSAGE_NAME>`). Typed disk persistence is generated only
// for these types. No-op when there are no `service_store` messages.
//
// Scope is the whole proto set; values are named from the message name. Names
// must be unique after snake_casing — a duplicate is a hard error because the
// colliding stores would share one enum value (and one on-disk snapshot path).
// Builder-driven generation rejects collisions earlier via
// parser.ValidateServiceStores; this check guards direct callers.
func GeneratePersistedStoreEnum(tempProtoDir string) error {
	dp, err := parser.NewDescriptorParser(tempProtoDir)
	if err != nil {
		return fmt.Errorf("failed to create descriptor parser for persisted store enum: %w", err)
	}

	seen := map[string]string{}
	var names []string
	for relPath, fileDesc := range dp.GetAllFiles() {
		if IsInfraProto(relPath) {
			continue
		}
		for i := range fileDesc.Messages {
			msg := fileDesc.Messages[i]
			if _, ok := msg.Annotations["service_store"]; !ok {
				continue
			}
			valName := strutil.ToUpperSnakeCase(msg.Name)
			if prev, dup := seen[valName]; dup {
				return fmt.Errorf("duplicate service_store message name for PersistedStore enum: %q and %q both map to PERSISTED_STORE_%s; service_store message names must be unique across all packages",
					prev, msg.Name, valName)
			}
			seen[valName] = msg.Name
			names = append(names, msg.Name)
		}
	}

	if len(names) == 0 {
		return nil
	}
	sort.Strings(names)

	var b strings.Builder
	b.WriteString(header.Copyright(consts.LangGo))
	b.WriteString("//\n")
	b.WriteString("// CODE GENERATED by tacplus — DO NOT EDIT.\n")
	b.WriteString("// One value per service_store-annotated message; used by typed disk persistence.\n\n")
	b.WriteString("syntax = \"proto3\";\n")
	b.WriteString("package persisted_store;\n\n")
	b.WriteString("// PersistedStore identifies a service_store that participates in typed disk\n")
	b.WriteString("// persistence (one value per store).\n")
	b.WriteString("enum PersistedStore {\n")
	b.WriteString("  PERSISTED_STORE_UNSPECIFIED = 0;\n")
	for i, name := range names {
		b.WriteString(fmt.Sprintf("  PERSISTED_STORE_%s = %d;\n", strutil.ToUpperSnakeCase(name), i+1))
	}
	b.WriteString("}\n")

	outDir := filepath.Join(tempProtoDir, "generated")
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return fmt.Errorf("failed to create generated proto dir: %w", err)
	}
	outPath := filepath.Join(outDir, "persisted_store.proto")
	if err := os.WriteFile(outPath, []byte(b.String()), 0o644); err != nil {
		return fmt.Errorf("failed to write persisted_store.proto: %w", err)
	}

	zap.L().Info("Generated PersistedStore enum",
		zap.Int("stores", len(names)),
		zap.String("file", "generated/persisted_store.proto"))
	return nil
}
