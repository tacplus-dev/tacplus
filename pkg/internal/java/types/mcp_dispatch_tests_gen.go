// The generated gate for the MCP dispatch seam (BIG GOAL 8 Phase 0, Java).
//
// Every service that publishes an MCP tool gets a self-test proving the thing
// the seam exists to do: a tool call reaches the service's own typed handler
// carrying a value the call never sent (the server-stamped principal or
// namespace), and a call that DOES send that value is refused before the handler
// is reached. Those two are the whole point of the guard order — a green build
// that does not run them proves only that the code compiles.
//
// A main-method self-test, not JUnit: that is how every generated Java test in
// this tree runs (chassis/x509/ImmutableCertChainTest,
// chassis/grpcserver/AuthorizerBehaviorTest, …), and it keeps the gate runnable
// with a plain `java -cp`.

// writeJavaMcpDispatchTestFile emits <Service>McpTest.java beside the dispatch.
func writeJavaMcpDispatchTestFile(svc *parser.ServiceInfo, tools []javaMcpTool, outputDir string, p javaMcpFileParams) error {
	if javaMcpCarrierMethod(svc) == nil {
		return nil
	}
	src := generateJavaMcpDispatchTest(svc, tools, p)
	outputPath := filepath.Join(outputDir, javaMcpClassName(svc.Name)+"Test.java")
	if err := os.WriteFile(outputPath, []byte(src), 0644); err != nil {
		return fmt.Errorf("failed to write MCP dispatch test for %s: %w", svc.Name, err)
	}
	return nil
}

// javaMcpTestCaller is the verified Caller every generated case dispatches as.
// A Caller is built from a token payload JSON, so the test's subject and
// namespace are stated once here and read back through the same claim accessors
// the dispatch uses.
const (
	javaMcpTestSubject   = "spiffe://example.test/mcp-test-caller"
	javaMcpTestNamespace = "/mcp-test"
)

func generateJavaMcpDispatchTest(svc *parser.ServiceInfo, tools []javaMcpTool, p javaMcpFileParams) string {
	cls := javaMcpClassName(svc.Name) + "Test"

	var b strings.Builder
	b.WriteString(header.Copyright(consts.LangJava))
	fmt.Fprintf(&b, `
// Generated by tacplus
//
// CODE GENERATED - DO NOT EDIT
//
// Source: %[4]s

package %[3]s;

%[5]s

/**
* %[2]s drives every published tool of %[1]s through the GENERATED dispatch and
* asserts the two properties the seam exists for:
*
* <ul>
*   <li>a tool call reaches the service's own typed handler method, carrying any
*       caller-scoped field STAMPED by the server — a value the tool call never
*       sent;</li>
*   <li>a tool call that names such a field itself is refused before the handler
*       is reached.</li>
* </ul>
*
* <p>A plain main-method self-test, like every other generated Java test here.
* Run it with {@code java -cp <classes> %[3]s.%[2]s}.
*/
public final class %[2]s {

    private static int failures = 0;

    private %[2]s() {}

    private static void check(boolean ok, String what) {
        if (!ok) {
            System.out.println("FAIL " + what);
            failures++;
        }
    }

    /** A Caller built from a verified-token payload, exactly as Auth.callerFromContext does. */
    private static Caller testCaller() {
        return new Caller("{\"sub\":\"%[6]s\",\"namespace\":\"%[7]s\"}", "mcp-test-request");
    }

    /** The text a tool result carries, whether it succeeded or failed. */
    private static String resultText(McpSchema.CallToolResult result) {
        StringBuilder sb = new StringBuilder();
        for (McpSchema.Content c : result.content()) {
            if (c instanceof McpSchema.TextContent text) {
                sb.append(text.text());
            }
        }
        return sb.toString();
    }

    private static boolean isError(McpSchema.CallToolResult result) {
        return Boolean.TRUE.equals(result.isError());
    }
`, svc.Name, cls, p.JavaPackage, p.ProtoFile, p.Imports, javaMcpTestSubject, javaMcpTestNamespace)

	b.WriteString(javaMcpTestStubHandler(svc, tools, p))
	b.WriteString(javaMcpTestToolSetCase(svc, tools))
	for _, t := range tools {
		b.WriteString(javaMcpTestToolCases(svc, t))
	}
	b.WriteString(javaMcpTestSessionCase(svc, tools, p))
	b.WriteString(javaMcpTestMain(svc, tools))
	b.WriteString("}\n")
	return b.String()
}

// javaMcpTestStubHandler renders the stub the dispatch is driven against.
//
// It implements the handler interface by RECORDING the request it was called
// with — which is the assertion: the test reads the stamped field back out of
// what the handler actually received, not out of what the dispatch claims to
// have sent. Every non-tool method of the interface throws, so a dispatch that
// reached the wrong rpc fails loudly rather than silently passing.
func javaMcpTestStubHandler(svc *parser.ServiceInfo, tools []javaMcpTool, p javaMcpFileParams) string {
	var b strings.Builder
	fmt.Fprintf(&b, `
    /**
    * StubHandler records the request each tool's typed handler method was called
    * with. A method the test does not drive throws, so a misrouted dispatch is a
    * failure rather than a silent pass.
    */
    private static final class StubHandler implements %[1]s.%[1]sHandler {
        private String lastMethod = "";
        private String lastRequest = "";
`, svc.Name)

	for _, t := range tools {
		b.WriteString(javaMcpTestToolStubMethod(t))
	}
	for _, decl := range p.NonToolHandlerDecls {
		b.WriteString(javaMcpTestThrowingStub(decl))
	}
	b.WriteString("    }\n")
	return b.String()
}

// javaMcpTestToolStubMethod renders one tool's stub method: it records the
// request it was called with — which IS the assertion, since the test reads the
// stamped field back out of what the handler actually received — and answers
// with a response the dispatch's own response validation accepts.
func javaMcpTestToolStubMethod(t javaMcpTool) string {
	name := methodNameLowerCamel(t.Method.Name)
	params := "Caller caller, " + t.InputType + " request"
	record := fmt.Sprintf("            this.lastMethod = %s;\n            this.lastRequest = request.toString();\n",
		javaQuote(t.Method.Name))
	if t.Page != nil {
		// A PAGE tool's handler is the keyset producer the gRPC PAGE wrapper
		// calls, so the stub declares that signature — and records the window it
		// was handed, which is what proves the tool call's page_size reached
		// PageParams rather than being dropped. It answers with an empty page;
		// the dispatch, not the handler, assembles the response envelope.
		return fmt.Sprintf(`
        @Override
        public CollectionRuntime.Page<%[1]s> %[2]s(Caller caller, %[3]s request, CollectionRuntime.PageParams page) {
            this.lastMethod = %[4]s;
            this.lastRequest = request.toString() + " page_limit=" + page.limit;
            return new CollectionRuntime.Page<>(java.util.List.of(), null, -1L);
        }
`, t.Page.ItemType, name, t.InputType, javaQuote(t.Method.Name))
	}
	if t.EmptyRequest {
		params = "Caller caller"
		record = fmt.Sprintf("            this.lastMethod = %s;\n            this.lastRequest = \"\";\n",
			javaQuote(t.Method.Name))
	}
	if t.EmptyResponse {
		return fmt.Sprintf(`
        @Override
        public void %s(%s) {
%s        }
`, name, params, record)
	}
	return fmt.Sprintf(`
        @Override
        public %s %s(%s) {
%s            return %s.newBuilder()%s.build();
        }
`, t.OutputType, name, params, record, t.OutputType, javaMcpTestResponseFill(t))
}

// javaMcpTestResponseFill sets the response's required scalar fields, so the
// generated RESPONSE validation the dispatch runs after the handler returns has
// something valid to pass on.
func javaMcpTestResponseFill(t javaMcpTool) string {
	var b strings.Builder
	for _, f := range t.ResponseRequiredScalars {
		fmt.Fprintf(&b, ".set%s(%s)", javaPascalField(f.Field), f.Java)
	}
	return b.String()
}

// javaMcpTestThrowingStub turns one handler-interface DECLARATION into a stub
// body that throws. Reusing the wrapper's own declaration is what makes the stub
// satisfy every rpc shape — unary, paged, watched, streaming — without a second
// renderer that would have to re-derive each signature.
func javaMcpTestThrowingStub(decl string) string {
	sig := strings.TrimSpace(strings.TrimSuffix(strings.TrimSpace(decl), ";"))
	name := sig
	if i := strings.Index(sig, "("); i >= 0 {
		if j := strings.LastIndex(sig[:i], " "); j >= 0 {
			name = sig[j+1 : i]
		}
	}
	return fmt.Sprintf(`
        @Override
        public %s {
            throw new IllegalStateException("%s is not an MCP tool and must not be reached by tool dispatch");
        }
`, sig, name)
}

// javaMcpTestToolSetCase renders the case asserting exactly the MCP rpcs — and
// no others — are published, with the tool NAME and the DESCRIPTION each carries.
func javaMcpTestToolSetCase(svc *parser.ServiceInfo, tools []javaMcpTool) string {
	var b strings.Builder
	fmt.Fprintf(&b, `
    /** The published tool set is exactly this service’s MCP tools. */
    private static void toolSetIsPublished() {
        java.util.List<McpSchema.Tool> published = %s.tools();
        check(published.size() == %d, "the tool set has %d tools, got " + published.size());
        java.util.Map<String, McpSchema.Tool> byName = new java.util.HashMap<>();
        for (McpSchema.Tool t : published) {
            byName.put(t.name(), t);
        }
`, javaMcpClassName(svc.Name), len(tools), len(tools))
	for _, t := range tools {
		fmt.Fprintf(&b, `        check(byName.containsKey(%[1]s), "the tool set publishes %[2]s");
        if (byName.containsKey(%[1]s)) {
            check(%[3]s.equals(byName.get(%[1]s).description()), "%[2]s carries its rpc's own doc comment as its description");
            check(Boolean.FALSE.equals(byName.get(%[1]s).inputSchema().get("additionalProperties")),
            "%[2]s declares additionalProperties: false");
`, javaQuote(t.ToolName), t.ToolName, javaQuote(t.Description))
		for _, f := range []string{t.PrincipalField, t.NamespaceField} {
			if f == "" {
				continue
			}
			fmt.Fprintf(&b, `            @SuppressWarnings("unchecked")
            java.util.Map<String, Object> __props%[3]s = (java.util.Map<String, Object>) byName.get(%[1]s).inputSchema().get("properties");
            check(__props%[3]s != null && !__props%[3]s.containsKey(%[2]s),
            "%[4]s's server-computed field is absent from its schema");
`, javaQuote(t.ToolName), javaQuote(f), javaPascalField(f), t.ToolName)
		}
		b.WriteString("        }\n")
	}
	// The paired control: an rpc of the SAME service that is not a tool reaches
	// neither the tool table nor the dispatch router.
	for _, m := range svc.Methods {
		if m.IsMcpTool() || m.Name == parser.McpCarrierRpcName(svc.Name) {
			continue
		}
		fmt.Fprintf(&b, `        check(!byName.containsKey(%s), "the non-tool rpc %s is not published as a tool");
`, javaQuote(strutil.ToSnakeCase(m.Name)), m.Name)
	}
	b.WriteString("    }\n")
	return b.String()
}

// javaMcpTestToolCases renders one tool's two cases: it reaches its typed
// handler with a server-stamped value, and it refuses a client-supplied one.
func javaMcpTestToolCases(svc *parser.ServiceInfo, t javaMcpTool) string {
	cls := javaMcpClassName(svc.Name)
	var b strings.Builder

	// A tool whose required request or response fields cannot be synthesized
	// gets the REFUSAL cases only: there is no one obviously-valid value for a
	// required enum or nested message, and a generated test that guesses wrong is
	// a false failure. Same rule Rust's Q7 and Go's Q8 took.
	if !javaMcpDrivable(t) {
		fmt.Fprintf(&b, `
    // "%s" has a required field this seam cannot synthesize a value for, so it
    // carries the refusal cases below and no reaches-its-handler case.
`, t.ToolName)
	} else if t.OwnerDefaultGuard != "" {
		b.WriteString(javaMcpTestOwnerDefaultCases(svc, t))
	} else {
		args := javaMcpTestArgumentMap(t, "")
		if t.Page != nil {
			args = javaMcpTestArgumentMap(t, fmt.Sprintf("%q, %d", "page_size", javaMcpTestPageSize))
		}
		fmt.Fprintf(&b, `
    /** The "%[1]s" tool call reaches %[2]s.%[3]s — the service's own typed handler method. */
    private static void %[4]sReachesItsTypedHandler() {
        StubHandler stub = new StubHandler();
        %[5]s.Surface surface = new %[5]s.Surface(stub, testCaller());
        McpSchema.CallToolResult result = surface.%[6]s(
        new McpSchema.CallToolRequest(%[7]s, %[8]s, null));
        check(!isError(result), "%[1]s succeeded, got: " + resultText(result));
        check("%[3]s".equals(stub.lastMethod), "%[1]s reached %[3]s, got: " + stub.lastMethod);
`, t.ToolName, svc.Name, t.Method.Name, methodNameLowerCamel(t.Method.Name), cls,
			javaMcpDispatchMethodName(t), javaQuote(t.ToolName), args)

		for _, s := range t.RequiredScalars {
			fmt.Fprintf(&b, `        check(stub.lastRequest.contains(%s), "%s decoded %s into the typed request");
`, javaQuote(s.Match), t.ToolName, s.Field)
		}
		if t.Page != nil {
			// PAGE: the tool call's own page_size reached the handler as the
			// window of a CollectionRuntime.PageParams — the same three-argument
			// call the gRPC PAGE wrapper makes.
			fmt.Fprintf(&b, `        check(stub.lastRequest.contains("page_limit=%[1]d"),
        "%[2]s passed its page_size to PageParams, got: " + stub.lastRequest);
`, javaMcpTestPageSize, t.ToolName)
		}
		// The stamp: a value the tool call never carried, read back off the request
		// the handler actually received.
		for _, f := range []struct{ field, value, what string }{
			{t.PrincipalField, javaMcpTestSubject, "(spec.principal)"},
			{t.NamespaceField, javaMcpTestNamespace, "(spec.namespace)"},
		} {
			if f.field == "" {
				continue
			}
			fmt.Fprintf(&b, `        // The %[3]s stamp: %[4]s was never in the arguments above.
        check(stub.lastRequest.contains(%[1]s), "%[2]s stamped the caller's own value into %[4]s");
`, javaQuote(f.value), t.ToolName, f.what, f.field)
		}
		b.WriteString("    }\n")
	}

	// The refusal case, one per server-computed field.
	for _, f := range []struct{ field, value, what string }{
		{t.PrincipalField, "spiffe://example.test/someone-else", "principal"},
		{t.NamespaceField, "/someone-elses-tenant", "namespace"},
	} {
		if f.field == "" {
			continue
		}
		fmt.Fprintf(&b, `
    /** A "%[1]s" call that names the server-computed %[2]s is refused before the handler is reached. */
    private static void %[3]sRefusesAClientSupplied%[4]s() {
        StubHandler stub = new StubHandler();
        %[5]s.Surface surface = new %[5]s.Surface(stub, testCaller());
        McpSchema.CallToolResult result = surface.%[6]s(
        new McpSchema.CallToolRequest(%[7]s, %[8]s, null));
        check(isError(result), "%[1]s refused a client-supplied %[2]s");
        check(resultText(result).contains("is not a tool argument"),
        "%[1]s said why it refused, got: " + resultText(result));
        check(stub.lastMethod.isEmpty(), "%[1]s never reached the handler, but it saw: " + stub.lastMethod);
    }
`, t.ToolName, f.field, methodNameLowerCamel(t.Method.Name), javaPascalField(f.field), cls,
			javaMcpDispatchMethodName(t), javaQuote(t.ToolName),
			javaMcpTestArgumentMap(t, fmt.Sprintf("%s, %s", javaQuote(f.field), javaQuote(f.value))))
	}
	return b.String()
}

// javaMcpTestOwnerDefaultCases renders the two cases of a tool whose
// (spec.owner_default) guard refuses its access: the gate's self-scoped caller
// is the row's owner and is refused before the handler, and the paired control —
// the same call from a caller whose grant carries a wider
// (spec.principal_scope) — reaches the handler. Without the control a guard that
// refused every caller would pass.
func javaMcpTestOwnerDefaultCases(svc *parser.ServiceInfo, t javaMcpTool) string {
	return fmt.Sprintf(`
    /** The "%[1]s" call from the row's own self-scoped principal is refused by (spec.owner_default). */
    private static void %[2]sRefusesTheRowOwner() {
        StubHandler stub = new StubHandler();
        %[3]s.Surface surface = new %[3]s.Surface(stub, testCaller());
        McpSchema.CallToolResult result = surface.%[4]s(
        new McpSchema.CallToolRequest(%[5]s, %[6]s, null));
        check(isError(result), "%[1]s refused the row owner");
        check(resultText(result).contains("(spec.owner_default)"),
        "%[1]s said why it refused, got: " + resultText(result));
        check(stub.lastMethod.isEmpty(), "%[1]s never reached the handler, but it saw: " + stub.lastMethod);
    }

    /** The same "%[1]s" call from a caller granted a wider (spec.principal_scope) reaches %[7]s. */
    private static void %[2]sAdmitsAWiderPrincipalScope() {
        StubHandler stub = new StubHandler();
        Caller wide = new Caller("{\"sub\":\"%[8]s\",\"namespace\":\"%[9]s\","
                + "\"service_entitlements\":{\"principal_scope\":\"PRINCIPAL_SCOPE_ANY\"}}", "mcp-test-request");
        %[3]s.Surface surface = new %[3]s.Surface(stub, wide);
        McpSchema.CallToolResult result = surface.%[4]s(
        new McpSchema.CallToolRequest(%[5]s, %[6]s, null));
        check(!isError(result), "%[1]s admitted a caller with a wider principal scope, got: " + resultText(result));
        check("%[7]s".equals(stub.lastMethod), "%[1]s reached %[7]s, got: " + stub.lastMethod);
    }
`, t.ToolName, methodNameLowerCamel(t.Method.Name), javaMcpClassName(svc.Name), javaMcpDispatchMethodName(t),
		javaQuote(t.ToolName), javaMcpTestArgumentMap(t, ""), t.Method.Name, javaMcpTestSubject, javaMcpTestNamespace)
}

// javaMcpTestArgumentMap renders the arguments map for a generated tool call:
// the required scalars with their synthetic values, plus `extra` when the case
// is the one that smuggles a server-computed field in.
// javaMcpTestPageSize is the page_size the generated gate asks a PAGE tool for.
// Below every resolved default and ceiling, so the clamp passes it through
// unchanged and the assertion reads the window the tool call actually asked for.
const javaMcpTestPageSize = 3

// javaMcpDrivable reports whether the gate can synthesize a valid call for this
// tool AND a response its own validation will accept. A PAGE tool's response is
// assembled by the dispatch, not by the stub, so the stub cannot fill a required
// response scalar for it — one of those means the refusal cases only.
func javaMcpDrivable(t javaMcpTool) bool {
	if !t.RequestSynthesizable || !t.ResponseSynthesizable {
		return false
	}
	return t.Page == nil || len(t.ResponseRequiredScalars) == 0
}

func javaMcpTestArgumentMap(t javaMcpTool, extra string) string {
	var parts []string
	for _, s := range t.RequiredScalars {
		parts = append(parts, javaQuote(s.Field)+", "+s.Java)
	}
	if extra != "" {
		parts = append(parts, extra)
	}
	if len(parts) == 0 {
		return "java.util.Map.of()"
	}
	return "java.util.Map.of(" + strings.Join(parts, ", ") + ")"
}

func javaMcpTestMain(svc *parser.ServiceInfo, tools []javaMcpTool) string {
	var b strings.Builder
	b.WriteString(`
    public static void main(String[] args) {
        toolSetIsPublished();
        mcpSessionServesItsTools();
`)
	for _, t := range tools {
		if javaMcpDrivable(t) && t.OwnerDefaultGuard != "" {
			fmt.Fprintf(&b, "        %[1]sRefusesTheRowOwner();\n        %[1]sAdmitsAWiderPrincipalScope();\n", methodNameLowerCamel(t.Method.Name))
		} else if javaMcpDrivable(t) {
			fmt.Fprintf(&b, "        %sReachesItsTypedHandler();\n", methodNameLowerCamel(t.Method.Name))
		}
		for _, f := range []string{t.PrincipalField, t.NamespaceField} {
			if f == "" {
				continue
			}
			fmt.Fprintf(&b, "        %sRefusesAClientSupplied%s();\n", methodNameLowerCamel(t.Method.Name), javaPascalField(f))
		}
	}
	fmt.Fprintf(&b, `        if (failures > 0) {
            System.out.println("%[1]sMcpTest: " + failures + " failure(s)");
            System.exit(1);
        }
        System.out.println("PASS %[1]sMcpTest");
    }
`, svc.Name)
	return b.String()
}

// javaMcpTestSessionCase renders the whole-session case: raw JSON-RPC frames in
// and out over the GENERATED carrier, rather than a direct call into the
// dispatch method the way the per-tool cases make.
//
// This is what proves the carriage, not just the dispatch: initialize (and that
// the instruction block comes back), notifications/initialized, tools/list (and
// that every published tool is listed), tools/call (and that the typed handler
// was reached with the server-stamped value), an undecodable frame (answered
// with -32700, and the session SURVIVES it), then a client hang-up (the carrier
// completes rather than failing the RPC).
//
// The tool driven is the first whose arguments this seam can synthesize; a
// service with none gets the frame-level cases and no tools/call.
func javaMcpTestSessionCase(svc *parser.ServiceInfo, tools []javaMcpTool, p javaMcpFileParams) string {
	var driven *javaMcpTool
	for i := range tools {
		// A tool its (spec.owner_default) guard refuses for this session's
		// self-scoped caller cannot be the one whose call reaches the handler.
		if javaMcpDrivable(tools[i]) && tools[i].OwnerDefaultGuard == "" {
			driven = &tools[i]
			break
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, `
    /**
    * A whole MCP session over the generated carrier, as raw JSON-RPC frames.
    *
    * <p>The per-tool cases above call the dispatch directly; this one goes
    * through %[2]s.serve — the transport, the SDK server and the
    * router — so it proves the CARRIAGE as well as the dispatch.
    */
    private static void mcpSessionServesItsTools() {
        StubHandler stub = new StubHandler();
        java.util.List<String> outbound = new java.util.concurrent.CopyOnWriteArrayList<>();
        java.util.concurrent.atomic.AtomicBoolean completed = new java.util.concurrent.atomic.AtomicBoolean(false);
        java.util.concurrent.atomic.AtomicReference<Throwable> failed = new java.util.concurrent.atomic.AtomicReference<>();
        StreamObserver<%[3]s> responses = new StreamObserver<%[3]s>() {
            @Override public void onNext(%[3]s value) { outbound.add(value.getPayload()); }
            @Override public void onError(Throwable t) { failed.set(t); }
            @Override public void onCompleted() { completed.set(true); }
        };
        StreamObserver<%[4]s> requests = %[2]s.serve(stub, testCaller(), responses);

        requests.onNext(%[4]s.newBuilder().setPayload(
        "{\"jsonrpc\":\"2.0\",\"id\":1,\"method\":\"initialize\",\"params\":{\"protocolVersion\":\"2025-06-18\","
        + "\"capabilities\":{},\"clientInfo\":{\"name\":\"%[1]sMcpTest\",\"version\":\"1\"}}}").build());
        check(outbound.size() == 1, "initialize was answered, got " + outbound.size() + " frame(s)");
        check(!outbound.isEmpty() && outbound.get(0).contains("Every tool here runs as you"),
        "initialize returned the instruction block");

        requests.onNext(%[4]s.newBuilder().setPayload(
        "{\"jsonrpc\":\"2.0\",\"method\":\"notifications/initialized\"}").build());

        requests.onNext(%[4]s.newBuilder().setPayload(
        "{\"jsonrpc\":\"2.0\",\"id\":2,\"method\":\"tools/list\"}").build());
        String listed = outbound.isEmpty() ? "" : outbound.get(outbound.size() - 1);
`, svc.Name, javaMcpClassName(svc.Name), p.FrameResponseType, p.FrameRequestType)

	for _, t := range tools {
		fmt.Fprintf(&b, `        check(listed.contains(%s), "tools/list listed %s");
`, javaQuote(`"name":"`+t.ToolName+`"`), t.ToolName)
	}

	if driven != nil {
		fmt.Fprintf(&b, `
        requests.onNext(%[1]s.newBuilder().setPayload(
        "{\"jsonrpc\":\"2.0\",\"id\":3,\"method\":\"tools/call\",\"params\":{\"name\":%[2]s,\"arguments\":%[3]s}}").build());
        check("%[4]s".equals(stub.lastMethod),
        "tools/call reached %[4]s, got: " + stub.lastMethod);
`, p.FrameRequestType, javaMcpTestJSONStringLiteral(driven.ToolName),
			javaMcpTestJSONArgumentLiteral(*driven), driven.Method.Name)
		for _, f := range []struct{ field, value string }{
			{driven.PrincipalField, javaMcpTestSubject},
			{driven.NamespaceField, javaMcpTestNamespace},
		} {
			if f.field == "" {
				continue
			}
			fmt.Fprintf(&b, `        check(stub.lastRequest.contains(%s),
        "the session stamped the caller's own value into %s — a value no frame above carried");
`, javaQuote(f.value), f.field)
		}
	} else {
		b.WriteString(`
        // No tool of this service has arguments this seam can synthesize, so the
        // session case drives the frame protocol and leaves tools/call to the
        // per-tool cases above.
`)
	}

	fmt.Fprintf(&b, `
        // An undecodable frame is answered, and the session survives it.
        int before = outbound.size();
        requests.onNext(%[1]s.newBuilder().setPayload("this is not a JSON-RPC frame").build());
        check(outbound.size() == before + 1, "an undecodable frame was answered");
        check(outbound.get(outbound.size() - 1).contains("-32700"),
        "an undecodable frame was answered with a JSON-RPC parse error, got: " + outbound.get(outbound.size() - 1));

        requests.onCompleted();
        check(completed.get(), "the carrier completed when the client hung up");
        check(failed.get() == null, "the carrier did not fail the RPC, got: " + failed.get());
    }
`, p.FrameRequestType)
	return b.String()
}

// javaMcpTestJSONStringLiteral renders a value as a JSON string that sits
// INSIDE an existing Java string literal — so the quotes around it are escaped
// once for Java and the result is spliced in, not quoted again.
func javaMcpTestJSONStringLiteral(v string) string {
	return "\\\"" + v + "\\\""
}

// javaMcpTestJSONArgumentLiteral renders a tool's synthesized arguments as a
// JSON object inside an existing Java string literal.
func javaMcpTestJSONArgumentLiteral(t javaMcpTool) string {
	var parts []string
	for _, s := range t.RequiredScalars {
		parts = append(parts, javaMcpTestJSONStringLiteral(s.Field)+":"+javaMcpTestJSONValue(s))
	}
	if t.Page != nil {
		parts = append(parts, javaMcpTestJSONStringLiteral("page_size")+":"+strconv.Itoa(javaMcpTestPageSize))
	}
	return "{" + strings.Join(parts, ",") + "}"
}

// javaMcpTestJSONValue renders one synthesized argument's value as JSON inside
// an existing Java string literal: a string is quote-escaped, a number or
// boolean passes through.
func javaMcpTestJSONValue(s javaMcpScalarArg) string {
	if strings.HasPrefix(s.Java, `"`) {
		return javaMcpTestJSONStringLiteral(s.Match)
	}
	return s.Java
}
