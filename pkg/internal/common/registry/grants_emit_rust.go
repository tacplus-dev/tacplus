func init() { registerGrantsEmitter("rust", emitRustGrantsHelper) }

// emitRustGrantsHelper writes <output>/grants/{mod.rs,grants.rs} (module grants).
// The generated module is the Rust counterpart of the Go helper in
// grants_emit.go and the language-agnostic reference in
// pkg/internal/common/verbs/entitlement.go: it embeds the EntitlementGrant
// catalog and exposes expand / normalize / contains_all / explain / lookup /
// is_wildcard over grant tokens. It depends only on the Rust standard library.
func emitRustGrantsHelper(cfg Config, grants []*spec.EntitlementGrantInfo) error {
	// Stable order for deterministic output.
	sorted := append([]*spec.EntitlementGrantInfo(nil), grants...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].GetToken() < sorted[j].GetToken() })

	var entries strings.Builder
	for _, g := range sorted {
		entries.WriteString("        m.insert(\n            ")
		entries.WriteString(rustStr(g.GetToken()))
		entries.WriteString(",\n            Grant {\n")
		entries.WriteString("                token: ")
		entries.WriteString(rustStr(g.GetToken()))
		entries.WriteString(",\n")
		entries.WriteString("                package: ")
		entries.WriteString(rustStr(g.GetPackage()))
		entries.WriteString(",\n")
		entries.WriteString("                service: ")
		entries.WriteString(rustStr(g.GetServiceName()))
		entries.WriteString(",\n")
		entries.WriteString("                rpc: ")
		entries.WriteString(rustStr(g.GetRpc()))
		entries.WriteString(",\n")
		entries.WriteString("                capability: ")
		entries.WriteString(rustStr(g.GetCapabilityScope()))
		entries.WriteString(",\n")
		entries.WriteString("                expands_to: &[")
		for i, t := range g.GetExpandsTo() {
			if i > 0 {
				entries.WriteString(", ")
			}
			entries.WriteString(rustStr(t))
		}
		entries.WriteString("],\n")
		entries.WriteString("            },\n        );\n")
	}

	// `mut` only when grants exist: an empty catalog would trip the generated
	// crate's unused_mut warning gate.
	letLine := "        let m: HashMap<&'static str, Grant> = HashMap::new();\n"
	if len(sorted) > 0 {
		letLine = "        let mut m: HashMap<&'static str, Grant> = HashMap::new();\n"
	}
	src := header.Copyright(consts.LangRust) + rustGrantsHeader + letLine + entries.String() + rustGrantsFooter

	dir := filepath.Join(cfg.OutputDir, "grants")
	if err := writeRustGrantsModule(dir, src); err != nil {
		return err
	}

	// Rust generation splits protobuf types into a sibling `*-types` crate so
	// reusable sys can depend on types without depending on the root model crate.
	// grpcserver imports this helper through that types crate, so mirror the
	// generated grants module there when the split crate is present. Keep the root
	// copy above for existing root-model imports.
	typesDir := filepath.Join(cfg.OutputDir, "types")
	if info, err := os.Stat(typesDir); err == nil && info.IsDir() {
		if err := writeRustGrantsModule(filepath.Join(typesDir, "grants"), src); err != nil {
			return err
		}
		if err := ensureRustModDecl(filepath.Join(typesDir, "mod.rs"), "grants"); err != nil {
			return err
		}
	}
	return nil
}

func writeRustGrantsModule(dir, src string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("failed to create grants dir: %w", err)
	}
	if err := os.WriteFile(filepath.Join(dir, "grants.rs"), []byte(src), 0o644); err != nil {
		return fmt.Errorf("failed to write grants.rs: %w", err)
	}
	if err := os.WriteFile(filepath.Join(dir, "mod.rs"), []byte(header.Copyright(consts.LangRust)+rustGrantsMod), 0o644); err != nil {
		return fmt.Errorf("failed to write grants/mod.rs: %w", err)
	}
	return nil
}

func ensureRustModDecl(modPath, module string) error {
	content, err := os.ReadFile(modPath)
	if err != nil {
		return fmt.Errorf("failed to read %s: %w", modPath, err)
	}
	decl := "pub mod " + module + ";"
	if strings.Contains(string(content), decl) {
		return nil
	}
	var b strings.Builder
	b.Write(content)
	if !strings.HasSuffix(string(content), "\n") {
		b.WriteString("\n")
	}
	b.WriteString(decl)
	b.WriteString("\n")
	if err := os.WriteFile(modPath, []byte(b.String()), 0o644); err != nil {
		return fmt.Errorf("failed to write %s: %w", modPath, err)
	}
	return nil
}

// rustStr renders a Go string as a Rust string literal.
func rustStr(s string) string {
	// Rust and Go share the same escape conventions for the characters that
	// appear in grant tokens (ASCII identifiers), so Go's quoting is safe here.
	return strconv.Quote(s)
}

