func init() { registerGrantsEmitter("python", emitPythonGrantsHelper) }

// emitPythonGrantsHelper writes <output>/<package-path>/grants/__init__.py,
// the generated entitlement-grant helper as a Python subpackage. cfg.OutputDir
// is the PROJECT output dir (where registry.json lives, consistent with the
// other languages); the Python package directory is derived from
// cfg.PackageBase (already normalized, dot-separated), so the emitted "grants"
// directory becomes an importable subpackage (<PackageBase>.grants) that
// setuptools' packages.find discovers, pip installs, and
// `python -m compileall` byte-compiles. Its behavior mirrors the Go helper
// in grants_emit.go and the reference in verbs/entitlement.go.
//
// Wildcard grants (PKG_ANY, PKG_<CAP>_ANY) carry a precomputed expands_to list,
// so the helper resolves wildcards by table lookup rather than re-derivation.
func emitPythonGrantsHelper(cfg Config, grants []*spec.EntitlementGrantInfo) error {
	// Stable order for deterministic output.
	sorted := append([]*spec.EntitlementGrantInfo(nil), grants...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].GetToken() < sorted[j].GetToken() })

	var entries strings.Builder
	for _, g := range sorted {
		entries.WriteString("    ")
		entries.WriteString(pyQuote(g.GetToken()))
		entries.WriteString(": Grant(")
		entries.WriteString("token=")
		entries.WriteString(pyQuote(g.GetToken()))
		entries.WriteString(", package=")
		entries.WriteString(pyQuote(g.GetPackage()))
		entries.WriteString(", service=")
		entries.WriteString(pyQuote(g.GetServiceName()))
		entries.WriteString(", rpc=")
		entries.WriteString(pyQuote(g.GetRpc()))
		entries.WriteString(", capability=")
		entries.WriteString(pyQuote(g.GetCapabilityScope()))
		entries.WriteString(", expands_to=(")
		exp := g.GetExpandsTo()
		for i, t := range exp {
			if i > 0 {
				entries.WriteString(", ")
			}
			entries.WriteString(pyQuote(t))
		}
		if len(exp) == 1 {
			// Single-element tuple needs a trailing comma.
			entries.WriteString(",")
		}
		entries.WriteString(")),\n")
	}

	src := pyGrantsHeader + entries.String() + pyGrantsFooter

	dir := filepath.Join(pythonPackageDir(cfg), "grants")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("failed to create grants dir: %w", err)
	}
	out := filepath.Join(dir, "__init__.py")
	if err := os.WriteFile(out, []byte(src), 0o644); err != nil {
		return fmt.Errorf("failed to write grants/__init__.py: %w", err)
	}
	return nil
}

// pythonPackageDir resolves the Python package directory under the project
// output dir from the dot-separated package base (e.g. "a.b.c" → <out>/a/b/c).
// PackageBase is normalized by the Python generator before registry.Generate
// runs, so a plain split suffices.
func pythonPackageDir(cfg Config) string {
	parts := append([]string{cfg.OutputDir}, strings.Split(cfg.PackageBase, ".")...)
	return filepath.Join(parts...)
}

// pyQuote renders s as a Python string literal. The grant token, package,
// service, RPC, and capability values are generated identifiers, so
// strconv.Quote (which escapes \, " and control chars the same way Python's
// double-quoted literals do) yields a valid Python string literal.
func pyQuote(s string) string {
	return strconv.Quote(s)
}

const pyGrantsHeader = `# Code generated by tacplus. DO NOT EDIT.
# Copyright (c) 2026 Second Star Cavalier LLC
#
# The grants package is the generated entitlement-grant helper. It embeds the
# EntitlementGrant catalog from registry.json and resolves grant tokens -- exact
# RPC grants (PKG_SERVICE_RPC) and wildcards (PKG_ANY, PKG_<CAP>_ANY) -- to
# explicit exact-grant sets. Runtime authorizers should normalize a grant list
# once and authorize by intersection with a call's exact MethodGrant token;
# wildcards are convenience input only and carry no runtime magic.

from typing import Dict, List, Optional, Tuple

__all__ = [
    "Grant",
    "lookup",
    "is_wildcard",
    "expand",
    "normalize",
    "unknown_tokens",
    "contains_all",
    "explain",
]


class Grant:
    """One entitlement grant token.

    Exact grants populate service/rpc; wildcard grants populate capability and
    expands_to (the precomputed exact tokens it implies).
    """

    __slots__ = ("token", "package", "service", "rpc", "capability", "expands_to")

    def __init__(
        self,
        token: str,
        package: str,
        service: str = "",
        rpc: str = "",
        capability: str = "",
        expands_to: Tuple[str, ...] = (),
    ) -> None:
        self.token = token
        self.package = package
        self.service = service
        self.rpc = rpc
        self.capability = capability
        self.expands_to = expands_to

    def is_exact(self) -> bool:
        return self.rpc != ""

    def is_wildcard(self) -> bool:
        return self.capability != ""

    def __repr__(self) -> str:  # pragma: no cover - debug aid only
        return "Grant(token=%r, package=%r)" % (self.token, self.package)


# _BY_TOKEN is the generated entitlement-grant catalog, keyed by grant token.
_BY_TOKEN: Dict[str, Grant] = {
`

const pyGrantsFooter = `}


def lookup(token: str) -> Optional[Grant]:
    """Return the Grant for a token, or None if it is not a known grant."""
    return _BY_TOKEN.get(token)


def is_wildcard(token: str) -> bool:
    """Report whether token is a package/capability wildcard grant."""
    g = _BY_TOKEN.get(token)
    return g is not None and g.capability != ""


def expand(token: str) -> List[str]:
    """Return the exact RPC grant tokens a token implies.

    A wildcard expands to its precomputed member tokens, a known exact token
    expands to itself, and an unknown token expands to an empty list.
    """
    g = _BY_TOKEN.get(token)
    if g is None:
        return []
    if g.capability != "":
        return list(g.expands_to)
    return [token]


def normalize(tokens: List[str]) -> List[str]:
    """Expand every token to exact grants, dedupe, and return a sorted set.

    This is the form a runtime authorizer should compute once and then authorize
    against by intersection.
    """
    seen = set()
    for t in tokens:
        for e in expand(t):
            seen.add(e)
    return sorted(seen)


def unknown_tokens(tokens: List[str]) -> List[str]:
    """Return the unknown input tokens that normalize would drop.

    Unknown grants stay fail-closed, but scope/authorization paths should log
    these values so grant vocabulary drift is visible.
    """
    return sorted({t for t in tokens if t not in _BY_TOKEN})


def contains_all(candidate: List[str], ceiling: List[str]) -> bool:
    """Report whether candidate's normalized grants are a subset of ceiling's.

    True means ceiling grants everything candidate does.
    """
    cap = set(normalize(ceiling))
    for g in normalize(candidate):
        if g not in cap:
            return False
    return True


def explain(token: str) -> List[str]:
    """Return the exact grant tokens a token implies, for operator/UI surfaces."""
    return expand(token)
`
