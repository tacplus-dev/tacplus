func TestLanguageConstants_AreNonEmpty(t *testing.T) {
	langs := []struct {
		name  string
		value string
	}{
		{"LangGo", LangGo},
		{"LangTypeScript", LangTypeScript},
		{"LangPython", LangPython},
		{"LangRust", LangRust},
		{"LangJava", LangJava},
	}

	for _, l := range langs {
		if l.value == "" {
			t.Errorf("%s must not be empty", l.name)
		}
	}
}

func TestLanguageConstants_ExpectedValues(t *testing.T) {
	tests := []struct {
		name     string
		got      string
		expected string
	}{
		{"LangGo", LangGo, "go"},
		{"LangTypeScript", LangTypeScript, "typescript"},
		{"LangPython", LangPython, "python"},
		{"LangRust", LangRust, "rust"},
		{"LangJava", LangJava, "java"},
	}

	for _, tt := range tests {
		if tt.got != tt.expected {
			t.Errorf("%s = %q, want %q", tt.name, tt.got, tt.expected)
		}
	}
}

func TestLanguageConstants_NoDuplicates(t *testing.T) {
	langs := []string{LangGo, LangTypeScript, LangPython, LangRust, LangJava}
	seen := make(map[string]bool, len(langs))

	for _, l := range langs {
		if seen[l] {
			t.Errorf("duplicate language constant value: %q", l)
		}
		seen[l] = true
	}
}

