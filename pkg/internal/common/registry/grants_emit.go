// grantsEmitter renders the generated entitlement-grant helper for one language
// and writes it under cfg.OutputDir. Each language registers its emitter from an
// init() in its own grants_emit_<lang>.go file, so adding a language touches no
// shared file (and a missing language is simply a no-op — incremental rollout
// must never fail generation).
type grantsEmitter func(cfg Config, grants []*spec.EntitlementGrantInfo) error

var grantsEmitters = map[string]grantsEmitter{}

// registerGrantsEmitter wires a language's emitter into the dispatch table.
func registerGrantsEmitter(language string, fn grantsEmitter) {
	grantsEmitters[language] = fn
}

// emitGrantsHelper renders the generated entitlement-grant helper for the
// configured language and writes it alongside registry.json. The helper is the
// per-language equivalent of pkg/internal/common/verbs/entitlement.go — it
// embeds the EntitlementGrant catalog (the same data emitted into
// registry.json.entitlement_grants) and exposes Expand / Normalize / ContainsAll
// / Explain over grant tokens so policy/operator/UI code can resolve wildcard
// grants to explicit RPC grants without re-parsing registry.json or reflecting
// over per-service enum fields.
//
// Wildcard grants (PKG_ANY, PKG_<CAP>_ANY) carry a precomputed ExpandsTo list in
// the catalog, so the per-language helper expands by table lookup rather than by
// re-deriving from method metadata.
func emitGrantsHelper(cfg Config, grants []*spec.EntitlementGrantInfo) error {
	if err := validateEntitlementGrantTokenCollisions(grants); err != nil {
		return fmt.Errorf("invalid entitlement grant catalog: %w", err)
	}
	if fn, ok := grantsEmitters[cfg.Language]; ok {
		return fn(cfg, grants)
	}
	// Not yet implemented for this language — emit nothing.
	return nil
}

func init() { registerGrantsEmitter("go", emitGoGrantsHelper) }

// emitGoGrantsHelper writes <output>/grants/grants.go (package grants).
func emitGoGrantsHelper(cfg Config, grants []*spec.EntitlementGrantInfo) error {
	// Stable order for deterministic output.
	sorted := append([]*spec.EntitlementGrantInfo(nil), grants...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].GetToken() < sorted[j].GetToken() })

	var entries strings.Builder
	for _, g := range sorted {
		entries.WriteString("\t")
		entries.WriteString(strconv.Quote(g.GetToken()))
		entries.WriteString(": {Token: ")
		entries.WriteString(strconv.Quote(g.GetToken()))
		entries.WriteString(", Package: ")
		entries.WriteString(strconv.Quote(g.GetPackage()))
		if g.GetServiceName() != "" {
			entries.WriteString(", Service: ")
			entries.WriteString(strconv.Quote(g.GetServiceName()))
		}
		if g.GetRpc() != "" {
			entries.WriteString(", RPC: ")
			entries.WriteString(strconv.Quote(g.GetRpc()))
		}
		if g.GetCapabilityScope() != "" {
			entries.WriteString(", Capability: ")
			entries.WriteString(strconv.Quote(g.GetCapabilityScope()))
		}
		if exp := g.GetExpandsTo(); len(exp) > 0 {
			entries.WriteString(", ExpandsTo: []string{")
			for i, t := range exp {
				if i > 0 {
					entries.WriteString(", ")
				}
				entries.WriteString(strconv.Quote(t))
			}
			entries.WriteString("}")
		}
		entries.WriteString("},\n")
	}

	src := goGrantsHeader + entries.String() + goGrantsFooter
	formatted, err := format.Source([]byte(src))
	if err != nil {
		return fmt.Errorf("failed to format generated grants.go: %w", err)
	}

	dir := filepath.Join(cfg.OutputDir, "grants")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("failed to create grants dir: %w", err)
	}
	out := filepath.Join(dir, "grants.go")
	if err := os.WriteFile(out, formatted, 0o644); err != nil {
		return fmt.Errorf("failed to write grants.go: %w", err)
	}
	return nil
}

const goGrantsHeader = `// Code generated by tacplus. DO NOT EDIT.
// Copyright (c) 2026 Second Star Cavalier LLC
//
// Package grants is the generated entitlement-grant helper. It embeds the
// EntitlementGrant catalog from registry.json and resolves grant tokens —
// exact RPC grants (PKG_SERVICE_RPC) and wildcards (PKG_ANY, PKG_<CAP>_ANY) —
// to explicit exact-grant sets. Runtime authorizers should Normalize a grant
// list once and authorize by intersection with a call's exact MethodGrant
// token; wildcards are convenience input only and carry no runtime magic.
package grants

import "sort"

// Grant describes one entitlement grant token.
type Grant struct {
	Token      string
	Package    string
	Service    string   // exact grants only
	RPC        string   // exact grants only
	Capability string   // wildcard grants only ("" for exact grants)
	ExpandsTo  []string // wildcard grants only: the exact tokens it implies
}

// byToken is the generated entitlement-grant catalog, keyed by grant token.
var byToken = map[string]Grant{
`

const goGrantsFooter = `}

// Lookup returns the Grant for a token and whether it is a known grant.
func Lookup(token string) (Grant, bool) { g, ok := byToken[token]; return g, ok }

// IsWildcard reports whether token is a package/capability wildcard grant.
func IsWildcard(token string) bool { g, ok := byToken[token]; return ok && g.Capability != "" }

// Expand returns the exact RPC grant tokens a token implies: a wildcard expands
// to its precomputed member tokens, a known exact token expands to itself, and
// an unknown token expands to nil.
func Expand(token string) []string {
	g, ok := byToken[token]
	if !ok {
		return nil
	}
	if g.Capability != "" {
		return append([]string(nil), g.ExpandsTo...)
	}
	return []string{token}
}

// Normalize expands every token to exact grants, removes duplicates, and returns
// a stable sorted set — the form a runtime authorizer should compute once and
// then authorize against by intersection.
func Normalize(tokens []string) []string {
	seen := make(map[string]bool, len(tokens))
	for _, t := range tokens {
		for _, e := range Expand(t) {
			seen[e] = true
		}
	}
	out := make([]string, 0, len(seen))
	for e := range seen {
		out = append(out, e)
	}
	sort.Strings(out)
	return out
}

// UnknownTokens returns the unknown input tokens that Normalize would drop.
// Unknown grants stay fail-closed (they imply no exact grants), but callers that
// scope or authorize external policy input should log these values so grant
// vocabulary drift is visible.
func UnknownTokens(tokens []string) []string {
	seen := make(map[string]bool, len(tokens))
	for _, t := range tokens {
		if _, ok := byToken[t]; !ok {
			seen[t] = true
		}
	}
	out := make([]string, 0, len(seen))
	for t := range seen {
		out = append(out, t)
	}
	sort.Strings(out)
	return out
}

// ContainsAll reports whether the normalized grants of candidate are a subset of
// those of ceiling — i.e. ceiling grants everything candidate does.
func ContainsAll(candidate, ceiling []string) bool {
	cap := make(map[string]bool)
	for _, g := range Normalize(ceiling) {
		cap[g] = true
	}
	for _, g := range Normalize(candidate) {
		if !cap[g] {
			return false
		}
	}
	return true
}

// Explain returns the exact grant tokens a token implies, for operator/UI
// "granting X grants these methods" surfaces.
func Explain(token string) []string { return Expand(token) }
`
