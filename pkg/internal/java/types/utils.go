	b.WriteString("        boolean isPublic = pem.contains(\"PUBLIC KEY-----\");\n")
	b.WriteString("        if (encType.startsWith(\"ENC_TYPE_X509_CERT\") && !isCertificate) {\n")
	b.WriteString("            throw new ProtoException(ProtoException.INVALID_ARGUMENT, String.format(\"field %s: value must be an X.509 certificate PEM\", fieldName));\n")
	b.WriteString("        }\n")
	b.WriteString("        if (encType.startsWith(\"ENC_TYPE_KEY_PRIVATE\") && !isPrivate) {\n")
