func TestBaseHeaderLines_IsSubsetOfHeaderLines(t *testing.T) {
	base := BaseHeaderLines()
	full := HeaderLines()

	if len(full) < len(base) {
		t.Fatal("HeaderLines() is shorter than BaseHeaderLines()")
	}

	for i, line := range base {
		if full[i] != line {
			t.Errorf("BaseHeaderLines line %d (%q) does not match HeaderLines line %d (%q)",
				i, line, i, full[i])
		}
	}
}

