// generateUtilsModule generates utils classes (ProtoException) into the shared source tree
func generateUtilsModule(outputDir string, config *tactype.Config) error {
	// Strip .types suffix from base package if present (types generator adds it)
	basePackage := config.JavaPackageBase
	basePackage = strings.TrimSuffix(basePackage, ".types")

	// ProtoException goes into types.sys.errors package
	javaPackage := basePackage + ".types.sys.errors"
	packagePath := strings.ReplaceAll(javaPackage, ".", string(filepath.Separator))
	// All generated code goes into the shared source tree: outputDir/src/main/java/
	srcDir := filepath.Join(outputDir, "src", "main", "java", packagePath)

	// Create directory structure
	if err := os.MkdirAll(srcDir, 0755); err != nil {
		return fmt.Errorf("failed to create errors/types directory: %w", err)
	}

	// Generate ProtoException.java
	if err := generateValidationExceptionClass(javaPackage, srcDir); err != nil {
		return fmt.Errorf("failed to generate ProtoException: %w", err)
	}

	zap.L().Info("Generated ProtoException into shared source tree")
	return nil
}

