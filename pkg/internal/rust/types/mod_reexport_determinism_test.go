package types

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestRustModReexportsAreSorted is a GEN-DET-1 regression guard.
// fixCrossModuleImports collects the modules a directory must re-export into a
// map, then wrote the `pub use crate::…;` block by ranging it — the comment
// above the loop said "Sort modules for consistent output" but no sort ever
// happened. Any mod.rs whose files reference >=2 sibling modules through
// `super::` therefore byte-diffed across otherwise-identical runs.
func TestRustModReexportsAreSorted(t *testing.T) {
	const runs = 20

	packageToDirMap := map[string]string{
		"key":   "types/sys/key",
		"token": "types/sys/token",
		"x509":  "types/sys/x509",
	}

	var first string
	for i := 0; i < runs; i++ {
		outputDir := t.TempDir()
		pkgDir := filepath.Join(outputDir, "types", "sys", "consumer")
		if err := os.MkdirAll(pkgDir, 0755); err != nil {
			t.Fatalf("mkdir: %v", err)
		}
		protoRs := "// @generated by prost-build\n" +
			"pub struct Consumer {}\n" +
			"// super::x509:: super::key:: super::token::\n"
		if err := os.WriteFile(filepath.Join(pkgDir, "consumer.rs"), []byte(protoRs), 0644); err != nil {
			t.Fatalf("write consumer.rs: %v", err)
		}
		if err := os.WriteFile(filepath.Join(pkgDir, "mod.rs"), []byte("pub mod consumer;\n"), 0644); err != nil {
			t.Fatalf("write mod.rs: %v", err)
		}

		if err := fixCrossModuleImports(outputDir, packageToDirMap); err != nil {
			t.Fatalf("fixCrossModuleImports: %v", err)
		}
		raw, err := os.ReadFile(filepath.Join(pkgDir, "mod.rs"))
		if err != nil {
			t.Fatalf("read mod.rs: %v", err)
		}
		rendered := string(raw)

		prev := -1
		for _, module := range []string{"key", "token", "x509"} {
			needle := "pub use crate::types::sys::" + module + "::" + module + ";"
			idx := strings.Index(rendered, needle)
			if idx < 0 {
				t.Fatalf("mod.rs missing re-export for %q:\n%s", module, rendered)
			}
			if idx < prev {
				t.Fatalf("mod.rs re-exports are not sorted (%q out of order):\n%s", module, rendered)
			}
			prev = idx
		}

		if i == 0 {
			first = rendered
			continue
		}
		if rendered != first {
			t.Fatalf("mod.rs is not byte-identical across runs (run %d differs); re-export order is nondeterministic", i)
		}
	}
}
