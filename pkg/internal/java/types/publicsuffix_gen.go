// publicSuffixChunkBytes bounds one string constant of PublicSuffixList.java:
// a class-file constant is at most 65535 bytes, so the table is emitted as
// several constants, each a run of whole rules joined by '\n', and split at
// class initialization (never one array element per rule: a static
// initializer is limited to 64 KB of bytecode).
const publicSuffixChunkBytes = 60000

// writeJavaSignInValidators writes into the Validation class the validators
// of (spec.assert_registrable_domain) and (spec.assert_not_address)
// (tacplus#224), the same semantics and refusal texts as the Go reference
// (pkg/internal/go/types/publicsuffix_gen.go). The table they match against
// lives in PublicSuffixList.java (PublicSuffixListJava), loaded on first use.
func writeJavaSignInValidators(b *strings.Builder) {
	b.WriteString(`
    // ============ Sign-in identity validators (tacplus#224) ============

    /**
     * Validates that a string is a domain name someone can register: ASCII
     * labels of letters, digits and hyphens, at least two, and not a public
     * suffix by the Public Suffix List snapshot in PublicSuffixList.
     * Corresponds to the (spec.assert_registrable_domain) annotation.
     */
    public static void validateRegistrableDomain(String name, String fieldName) throws ProtoException {
        String refusal = registrableDomainRefusal(name);
        if (refusal != null) {
            throw new ProtoException(ProtoException.INVALID_ARGUMENT, String.format("field %s must be a registrable domain name: %s", fieldName, refusal));
        }
    }

    /**
     * Returns null when name is a registrable domain name, else the refusal:
     * "not a domain name" or "a public suffix".
     */
    static String registrableDomainRefusal(String name) {
        if (name.isEmpty() || name.length() > 253) {
            return "not a domain name";
        }
        int start = 0;
        while (true) {
            int end = name.indexOf('.', start);
            if (end < 0) {
                end = name.length();
            }
            int len = end - start;
            if (len == 0 || len > 63 || name.charAt(start) == '-' || name.charAt(end - 1) == '-') {
                return "not a domain name";
            }
            for (int i = start; i < end; i++) {
                char c = name.charAt(i);
                if (!(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' || c == '-')) {
                    return "not a domain name";
                }
            }
            if (end == name.length()) {
                break;
            }
            start = end + 1;
        }
        if (isPublicSuffix(name.toLowerCase(java.util.Locale.ROOT))) {
            return "a public suffix";
        }
        return null;
    }

    private static boolean isPublicSuffix(String name) {
        int dot = name.indexOf('.');
        if (dot < 0) {
            return true;
        }
        if (PublicSuffixList.contains("!" + name)) {
            return false;
        }
        if (PublicSuffixList.contains(name)) {
            return true;
        }
        return PublicSuffixList.contains("*." + name.substring(dot + 1));
    }

    /**
     * Validates that a string is not address-shaped: it contains no '@'.
     * Corresponds to the (spec.assert_not_address) annotation.
     */
    public static void validateNotAddress(String s, String fieldName) throws ProtoException {
        if (s.indexOf('@') >= 0) {
            throw new ProtoException(ProtoException.INVALID_ARGUMENT, String.format("field %s must not be address-shaped: address-shaped", fieldName));
        }
    }
`)
}

// PublicSuffixListJava returns PublicSuffixList.java for javaPackage: the
// Public Suffix List table, publicsuffix.Rules(), as a sorted String[] built
// at class initialization from a few string constants, with a binary-search
// lookup.
func PublicSuffixListJava(javaPackage string) string {
	var b strings.Builder
	b.WriteString(header.GeneratedHeader(consts.LangJava, ""))
	fmt.Fprintf(&b, "package %s;\n\n", javaPackage)
	fmt.Fprintf(&b, `/**
 * The Public Suffix List (publicsuffix.org, MPL-2.0), version %s, in ASCII
 * (each Unicode label in its xn-- form), lowercase, sorted; wildcard rules keep
 * their "*." prefix and exceptions their "!". Used by
 * Validation.validateRegistrableDomain (spec.assert_registrable_domain).
 *
 * Generated by tacplus
 */
final class PublicSuffixList {
    private PublicSuffixList() {}

    // The rules joined by '\n', split across constants: one class-file string
    // constant is limited to 65535 bytes.
    private static final String[] PARTS = {
`, publicsuffix.Version())
	var chunk strings.Builder
	flush := func() {
		if chunk.Len() == 0 {
			return
		}
		fmt.Fprintf(&b, "        \"%s\",\n", chunk.String())
		chunk.Reset()
	}
	n := 0
	for _, r := range publicsuffix.Rules() {
		// Rules are lowercase ASCII without quotes or backslashes; each costs
		// len(r)+1 constant bytes ("\n" is one byte once compiled).
		if n+len(r)+1 > publicSuffixChunkBytes {
			flush()
			n = 0
		}
		chunk.WriteString(r)
		chunk.WriteString(`\n`)
		n += len(r) + 1
	}
	flush()
	b.WriteString(`    };

    private static final String[] RULES = load();

    private static String[] load() {
        java.util.ArrayList<String> rules = new java.util.ArrayList<>();
        for (String part : PARTS) {
            int start = 0;
            int end;
            while ((end = part.indexOf('\n', start)) >= 0) {
                rules.add(part.substring(start, end));
                start = end + 1;
            }
        }
        return rules.toArray(new String[0]);
    }

    /** Reports whether rule is in the table. */
    static boolean contains(String rule) {
        return java.util.Arrays.binarySearch(RULES, rule) >= 0;
    }
}
`)
	return b.String()
}

// writePublicSuffixList writes PublicSuffixList.java next to Validation.java.
func writePublicSuffixList(srcDir, javaPackage string) error {
	outputPath := filepath.Join(srcDir, "PublicSuffixList.java")
	if err := os.WriteFile(outputPath, []byte(PublicSuffixListJava(javaPackage)), 0644); err != nil {
		return fmt.Errorf("failed to write PublicSuffixList.java: %w", err)
	}
	return nil
}
