package consts

// Languages defines all supported programming languages
const (
	LangGo         = "go"
	LangTypeScript = "typescript"
	LangPython     = "python"
	LangRust       = "rust"
	LangJava       = "java"
	LangSwift      = "swift"
	LangCSharp     = "csharp"
)

// HeaderLines returns the standard generated code header as a slice of strings.
// The copyright line is not part of it: see header.SetCopyright.
// Each line can then be prefixed with the appropriate comment syntax for the language
func HeaderLines() []string {
	return []string{
		"Generated by tacplus",
		"",
		"CODE GENERATED - DO NOT EDIT",
		"This file is automatically generated by the tacplus compiler.",
		"Manual modifications will be overwritten on next generation.",
		"",
		"IMPORTANT FOR AGENTS: Do NOT modify this generated code.",
		"If changes are needed, update the tacplus compiler at:",
		"gitlab.com/seabeam/schematic/tacplus",
		"",
		"PUBLIC SURFACE CONTRACT:",
		"Generated raw transport clients and internal wiring are tacplus implementation details.",
		"Do not import or instantiate those generated internals directly from consumer code.",
		"Consumer code should use the generated Service Manager (SM), handler interfaces,",
		"and documented helpers instead.",
		"If a required capability is only reachable by importing raw generated internals,",
		"it is almost certainly a tacplus bug; please report it.",
	}
}

// HeaderLinesWithSource returns the header with a source file reference
func HeaderLinesWithSource(source string) []string {
	lines := HeaderLines()
	if source != "" {
		lines = append(lines, "")
		lines = append(lines, "Source: "+source)
	}
	return lines
}

// BaseHeaderLines returns just the generator line (for simple files)
func BaseHeaderLines() []string {
	return []string{
		"Generated by tacplus",
	}
}

// ExampleHeaderLines returns the header for generated example files.
// Unlike library code, examples are meant to be modified by developers.
func ExampleHeaderLines(source string) []string {
	lines := []string{
		"Generated by tacplus as an example implementation.",
		"",
		"This file was automatically generated from the proto definition",
		"to demonstrate how to use the generated types and services.",
		"Feel free to modify this code to suit your needs.",
	}
	if source != "" {
		lines = append(lines, "")
		lines = append(lines, "Source: "+source)
	}
	return lines
}
