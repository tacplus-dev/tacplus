// The generated regression gate for the MCP dispatch seam.
//
// Generated rather than hand-written for the same reason the dispatch itself is:
// these assert the properties that must not silently regress in ANY service —
// that a tool call reaches its own typed handler with the arguments decoded,
// that a caller-scoped field is stamped from the verified caller and refused as
// an argument, and that a whole MCP session rides the generated gRPC transport.
// A service that grows an MCP tool gets the gate with it.

// goMcpTestFileName is the test file the gate lands in, next to the dispatch.
func goMcpTestFileName(serviceName string) string {
	return strutil.ToSnakeCase(serviceName) + "_mcp_test.go"
}

// writeGoMcpDispatchTestFile emits <service>_mcp_test.go beside the dispatch.
func writeGoMcpDispatchTestFile(svc *parser.ServiceInfo, outputDir string, p goMcpFileParams, san *egressSanitizer) error {
	if goMcpCarrierMethod(svc) == nil {
		return nil
	}
	tools, err := goMcpTools(svc, p.ServicePackage, san)
	if err != nil {
		return fmt.Errorf("failed to resolve MCP tools for %s: %w", svc.Name, err)
	}
	src := generateGoMcpDispatchTests(svc, tools, p)
	outputPath := filepath.Join(outputDir, goMcpTestFileName(svc.Name))
	formatted, err := imports.Process(outputPath, []byte(src), nil)
	if err != nil {
		zap.L().Warn("failed to goimports MCP dispatch tests, trying format.Source", zap.Error(err))
		formatted, err = format.Source([]byte(src))
		if err != nil {
			zap.L().Warn("failed to format MCP dispatch tests", zap.Error(err))
			formatted = []byte(src)
		}
	}
	if err := os.WriteFile(outputPath, formatted, 0644); err != nil {
		return fmt.Errorf("failed to write MCP dispatch tests for %s: %w", svc.Name, err)
	}
	return nil
}

func generateGoMcpDispatchTests(svc *parser.ServiceInfo, tools []goMcpTool, p goMcpFileParams) string {
	carrier := goMcpCarrierMethod(svc)
	prefix := goMcpPrefix(svc.Name)
	frameIn := goTypeRef(carrier.FullInputType, carrier.InputType, p.ServicePackage)
	frameOut := goTypeRef(carrier.FullOutputType, carrier.OutputType, p.ServicePackage)

	var crossImports strings.Builder
	for pkg, dir := range p.CrossPackageTypes {
		if dir == "" || !p.used[pkg] || pkg == "google.protobuf" {
			continue
		}
		var importPath string
		switch {
		case strings.HasPrefix(dir, "services"):
			importPath = fmt.Sprintf("%s/types/%s/%s", p.ModuleBasePath, dir, pkg)
		case filepath.Base(dir) == pkg:
			importPath = fmt.Sprintf("%s/types/%s", p.ModuleBasePath, dir)
		default:
			importPath = fmt.Sprintf("%s/types/%s/%s", p.ModuleBasePath, dir, pkg)
		}
		fmt.Fprintf(&crossImports, "\n\t%s_pb \"%s\"", pkg, importPath)
	}
	if goMcpHasPageTool(tools) {
		// The PAGE stub handler's own signature names collection.PageParams /
		// collection.Page; goimports cannot resolve that local package by name.
		fmt.Fprintf(&crossImports, "\n\t\"%s/chassis/collection\"", p.ModuleBasePath)
	}

	var b strings.Builder
	b.WriteString(header.Copyright(consts.LangGo))
	fmt.Fprintf(&b, `
// Generated by service generator
//
// CODE GENERATED - DO NOT EDIT
//
// The generated regression gate for %[1]s's MCP tool surface. It drives real
// tool calls through the generated dispatch against a stub handler, so a change
// that stops a tool reaching its typed handler, stops a caller-scoped field
// being stamped, or stops the session riding the gRPC carrier fails here.

package %[2]s

import (
	"context"
	"encoding/json"
	"io"
	"strings"
	"testing"

	"%[8]s/mcp"

	types "%[3]s"
	"%[4]s"
	wrapperToken "%[5]s/chassis/token"%[6]s
	"google.golang.org/grpc"
	"google.golang.org/grpc/codes"
	"google.golang.org/grpc/metadata"
	"google.golang.org/grpc/status"
)

// The subject and namespace the test caller's token carries. Every
// server-stamped field below must come out equal to one of them.
const (
	%[7]sTestSubject   = "spiffe://example/tenants/acme/users/alice"
	%[7]sTestNamespace = "/example/tenants/acme"
)

func %[7]sTestCaller() *servicemanager.Caller {
	tok := wrapperToken.NewImmutableToken(nil).
		SetSubject(%[7]sTestSubject).
		SetNamespace(%[7]sTestNamespace)
	return servicemanager.NewCaller(tok, "mcp-test")
}

// %[7]sReportingHandler reports what its MCP tools were called with, by failing
// with the request's own rendering. Reporting through the error is what lets the
// assertions below read the request the dispatch built without the stub having
// to synthesize a valid response for it.
//
// The embedded interface satisfies every other method of %[1]sHandler: it is
// nil, so a dispatch that called one would panic — which is the assertion that
// only the tool under test is reached.
type %[7]sReportingHandler struct {
	%[1]sHandler
}

`, svc.Name, p.PackageName, p.TypesModulePath, p.ServiceManagerImportPath,
		p.ModuleBasePath, crossImports.String(), prefix, goMcpSdkModule)

	for _, t := range tools {
		args := "ctx context.Context, _ *servicemanager.Caller, req *" + t.InputType
		report := `"MCP_CALLED " + req.String()`
		if t.EmptyRequest {
			args = "ctx context.Context, _ *servicemanager.Caller"
			report = strconv.Quote("MCP_CALLED " + t.Method.Name)
		}
		results := "(*" + t.OutputType + ", error)"
		ret := "return nil, status.Error(codes.Internal, " + report + ")"
		if t.EmptyResponse {
			results = "error"
			ret = "return status.Error(codes.Internal, " + report + ")"
		}
		if t.Page != nil {
			// A PAGE tool's handler is the keyset producer the gRPC PAGE wrapper
			// calls, so the stub declares that signature — and reports the window
			// it was handed, which is what proves the tool call's page_size
			// reached PageParams rather than being dropped.
			args += ", page collection.PageParams"
			report = `"MCP_CALLED " + req.String() + " page_limit=" + strconv.Itoa(page.Limit)`
			results = "(collection.Page[*" + t.Page.ItemType + "], error)"
			ret = "return collection.Page[*" + t.Page.ItemType + "]{}, status.Error(codes.Internal, " + report + ")"
		}
		fmt.Fprintf(&b, `func (h *%[1]sReportingHandler) %[2]s(%[3]s) %[4]s {
	_ = ctx
	%[5]s
}

`, prefix, t.Method.Name, args, results, ret)
	}

	// The tool set is published.
	fmt.Fprintf(&b, `// Test%[1]sMcpToolSetIsPublished: every MCP tool of this service reaches the
// published tool set, with a schema the SDK will serve.
func Test%[1]sMcpToolSetIsPublished(t *testing.T) {
	tools := %[1]sMcpTools()
	if len(tools) != %[2]d {
		t.Fatalf("the published tool set is not the declared one: %%d tools", len(tools))
	}
	byName := map[string]*mcp.Tool{}
	for _, tool := range tools {
		byName[tool.Name] = tool
	}
`, svc.Name, len(tools))
	for _, t := range tools {
		fmt.Fprintf(&b, `	if tool, ok := byName[%[1]s]; !ok {
		t.Fatalf("%[2]s is declared RPC_PRINCIPAL_MCP but is not published")
	} else if raw, ok := tool.InputSchema.(json.RawMessage); !ok {
		t.Fatalf("%[2]s publishes no generated input schema")
	} else if !json.Valid(raw) {
		t.Fatalf("%[2]s publishes an input schema that is not JSON: %%s", raw)
	}
`, strconv.Quote(t.ToolName), t.ToolName)
	}
	// An rpc of the same service that is not a tool must not be published.
	for _, m := range svc.Methods {
		if m.IsMcpTool() || m == carrier {
			continue
		}
		fmt.Fprintf(&b, `	if _, ok := byName[%[1]s]; ok {
		t.Fatalf("%[2]s is not an MCP tool but was published as one")
	}
`, strconv.Quote(strutil.ToSnakeCase(m.Name)), m.Name)
	}
	b.WriteString("}\n")

	for _, t := range tools {
		b.WriteString(goMcpToolTests(svc.Name, prefix, t))
	}

	b.WriteString(goMcpSessionTest(svc.Name, prefix, frameIn, frameOut, tools))
	return b.String()
}

// goMcpToolTests renders one tool's dispatch tests. A tool whose required
// arguments cannot be synthesized (a required enum or nested message) gets the
// refusal tests only — there is no obviously-valid call to drive.
func goMcpToolTests(serviceName, prefix string, t goMcpTool) string {
	var b strings.Builder
	surface := serviceName + "McpSurface"
	testName := serviceName + "Mcp" + t.Method.Name

	if goMcpDrivable(t) {
		fmt.Fprintf(&b, `
// Test%[1]sReachesItsTypedHandler: a tool call reaches its own typed handler,
// with the arguments decoded into the rpc's request message.
func Test%[1]sReachesItsTypedHandler(t *testing.T) {
	surface := New%[2]s(&%[3]sReportingHandler{}, %[3]sTestCaller())
	result, err := surface.%[4]s(context.Background(), json.RawMessage(%[5]s))
	if err != nil {
		t.Fatalf("the dispatch failed as a protocol error rather than a tool result: %%v", err)
	}
	reported := %[3]sResultText(t, result)
	if !strings.HasPrefix(reported, "MCP_CALLED") {
		t.Fatalf("the tool call did not reach its typed handler: %%s", reported)
	}
`, testName, surface, prefix, goMcpDispatchFnName(t), strconv.Quote(goMcpTestArgsJSON(t)))
		for _, a := range t.RequiredScalars {
			fmt.Fprintf(&b, `	if !strings.Contains(reported, %[1]s) {
		t.Fatalf("the handler did not receive %[2]s: %%s", reported)
	}
`, strconv.Quote(a.Match), a.Field)
		}
		if t.Page != nil {
			fmt.Fprintf(&b, `	// PAGE: the tool call's own page_size reached the handler as the window of
	// a collection.PageParams — the same three-argument call the gRPC PAGE
	// wrapper makes.
	if !strings.Contains(reported, "page_limit=%[1]d") {
		t.Fatalf("the tool call's page_size did not reach PageParams: %%s", reported)
	}
`, goMcpTestPageSize)
		}
		if t.PrincipalField != "" {
			fmt.Fprintf(&b, `	// (spec.principal): stamped by the dispatch from the verified caller, so
	// the handler sees it without the tool call ever carrying it.
	if !strings.Contains(reported, %[1]sTestSubject) {
		t.Fatalf("%[2]s was not stamped from the caller: %%s", reported)
	}
`, prefix, t.PrincipalField)
		}
		if t.NamespaceField != "" {
			fmt.Fprintf(&b, `	// (spec.namespace): stamped by the dispatch from the caller's namespace claim.
	if !strings.Contains(reported, %[1]sTestNamespace) {
		t.Fatalf("%[2]s was not stamped from the caller: %%s", reported)
	}
`, prefix, t.NamespaceField)
		}
		b.WriteString("}\n")
	}

	for _, f := range []struct{ marker, field, value string }{
		{"spec.principal", t.PrincipalField, "spiffe://example/tenants/acme/users/mallory"},
		{"spec.namespace", t.NamespaceField, "/example/tenants/rival"},
	} {
		if f.field == "" {
			continue
		}
		fmt.Fprintf(&b, `
// Test%[1]sRefusesAClientSupplied%[2]s: (%[3]s) %[4]s is the server's to set.
// A tool call that names it is refused outright rather than silently overridden,
// and the handler is never reached.
func Test%[1]sRefusesAClientSupplied%[2]s(t *testing.T) {
	surface := New%[5]s(&%[6]sReportingHandler{}, %[6]sTestCaller())
	result, err := surface.%[7]s(context.Background(), json.RawMessage(%[8]s))
	if err != nil {
		t.Fatalf("the dispatch failed as a protocol error rather than a tool result: %%v", err)
	}
	if !result.IsError {
		t.Fatalf("a client-supplied %[4]s was accepted")
	}
	refused := %[6]sResultText(t, result)
	if strings.HasPrefix(refused, "MCP_CALLED") {
		t.Fatalf("a client-supplied %[4]s reached the handler: %%s", refused)
	}
	if !strings.Contains(refused, "not a tool argument") {
		t.Fatalf("unexpected refusal: %%s", refused)
	}
}
`, testName, toGoFieldName(f.field), f.marker, f.field, surface, prefix,
			goMcpDispatchFnName(t), strconv.Quote(fmt.Sprintf(`{%q: %q}`, f.field, f.value)))
	}

	return b.String()
}

// goMcpDrivable reports whether the generated gate can synthesize a valid call
// for this tool. A PAGE tool always is: page_size alone is a valid call.
func goMcpDrivable(t goMcpTool) bool {
	return t.EmptyRequest || t.Page != nil || len(t.RequiredScalars) > 0 || t.PrincipalField != "" || t.NamespaceField != ""
}

// goMcpTestPageSize is the page_size the gate asks a PAGE tool for. Below every
// resolved default and ceiling, so the clamp passes it through unchanged and the
// assertion reads the window the tool call actually asked for.
const goMcpTestPageSize = 3

// goMcpTestArgsJSON is the arguments object the gate calls the tool with: every
// required scalar, and nothing the server computes.
func goMcpTestArgsJSON(t goMcpTool) string {
	var args []string
	for _, a := range t.RequiredScalars {
		args = append(args, fmt.Sprintf("%s: %s", strconv.Quote(a.Field), a.JSON))
	}
	if t.Page != nil {
		args = append(args, fmt.Sprintf("%q: %d", "page_size", goMcpTestPageSize))
	}
	return "{" + strings.Join(args, ", ") + "}"
}

// goMcpSessionTest renders the end-to-end gate: a whole MCP session — the
// initialize handshake, tools/list and one tools/call — driven as raw JSON-RPC
// frames over the generated gRPC transport.
func goMcpSessionTest(serviceName, prefix, frameIn, frameOut string, tools []goMcpTool) string {
	var driven goMcpTool
	var haveDriven bool
	for _, t := range tools {
		if goMcpDrivable(t) {
			driven, haveDriven = t, true
			break
		}
	}

	var callBlock string
	if haveDriven {
		callBlock = fmt.Sprintf(`	called := ask(t, stream, `+"`"+`{"jsonrpc":"2.0","id":3,"method":"tools/call","params":{"name":%s,"arguments":%s}}`+"`"+`)
	if !strings.Contains(called, "MCP_CALLED") {
		t.Fatalf("the tool call did not reach its typed handler over the session: %%s", called)
	}
`, strconv.Quote(driven.ToolName), goMcpTestArgsJSON(driven))
	}

	return fmt.Sprintf(`
// Test%[1]sMcpSessionServesItsTools drives a whole MCP session over the
// generated gRPC carrier: the initialize handshake, tools/list, and one
// tools/call that has to reach the typed handler.
func Test%[1]sMcpSessionServesItsTools(t *testing.T) {
	stream := new%[2]sTestStream()
	done := make(chan error, 1)
	go func() {
		done <- serve%[1]sMcpSession(context.Background(), &%[2]sReportingHandler{}, %[2]sTestCaller(), stream)
	}()

	initialized := ask(t, stream, `+"`"+`{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2025-06-18","capabilities":{},"clientInfo":{"name":"tacplus-gate","version":"1"}}}`+"`"+`)
	if !strings.Contains(initialized, %[3]sMcpInstructions[:24]) {
		t.Fatalf("the session did not serve its instructions: %%s", initialized)
	}
	stream.in <- `+"`"+`{"jsonrpc":"2.0","method":"notifications/initialized"}`+"`"+`

	listed := ask(t, stream, `+"`"+`{"jsonrpc":"2.0","id":2,"method":"tools/list"}`+"`"+`)
	for _, tool := range %[3]sMcpTools() {
		if !strings.Contains(listed, tool.Name) {
			t.Fatalf("%%s is missing from tools/list: %%s", tool.Name, listed)
		}
	}

%[4]s
	// An undecodable frame is answered, not fatal: the session survives it.
	if parseErr := ask(t, stream, "not a json-rpc frame"); !strings.Contains(parseErr, "-32700") {
		t.Fatalf("an undecodable frame was not answered with a parse error: %%s", parseErr)
	}

	close(stream.in)
	if err := <-done; err != nil {
		t.Fatalf("a client hang-up failed the carrier RPC: %%v", err)
	}
}

// ask writes one JSON-RPC frame to the session and returns the next frame the
// session writes back.
func ask(t *testing.T, stream *%[2]sTestStream, frame string) string {
	t.Helper()
	stream.in <- frame
	return <-stream.out
}

// %[2]sResultText is the text a tool result carries — the handler's report, or
// the dispatch's refusal.
func %[2]sResultText(t *testing.T, result *mcp.CallToolResult) string {
	t.Helper()
	if len(result.Content) == 0 {
		t.Fatalf("the tool result carries no content")
	}
	text, ok := result.Content[0].(*mcp.TextContent)
	if !ok {
		t.Fatalf("the tool result's content is not text")
	}
	return text.Text
}

// %[2]sTestStream stands in for the gRPC bidi stream the carrier RPC carries.
type %[2]sTestStream struct {
	grpc.ServerStream
	in  chan string
	out chan string
}

func new%[2]sTestStream() *%[2]sTestStream {
	return &%[2]sTestStream{in: make(chan string, 8), out: make(chan string, 8)}
}

func (s *%[2]sTestStream) Context() context.Context { return context.Background() }

func (s *%[2]sTestStream) Recv() (*%[5]s, error) {
	payload, ok := <-s.in
	if !ok {
		return nil, io.EOF
	}
	return &%[5]s{Payload: payload}, nil
}

func (s *%[2]sTestStream) Send(frame *%[6]s) error {
	s.out <- frame.GetPayload()
	return nil
}

func (s *%[2]sTestStream) SetHeader(metadata.MD) error  { return nil }
func (s *%[2]sTestStream) SendHeader(metadata.MD) error { return nil }
func (s *%[2]sTestStream) SetTrailer(metadata.MD)       {}
`, serviceName, prefix, serviceName, callBlock, frameIn, frameOut)
}
