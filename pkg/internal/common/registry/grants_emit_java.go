package registry

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	spec "gitlab.com/secondstarcavalier/schematic/tacplus/target/proto/spec/sys"
)

func init() { registerGrantsEmitter("java", emitJavaGrantsHelper) }

// emitJavaGrantsHelper writes the generated entitlement-grant helper for Java to
// <output>/src/main/java/<packagePath>/grants/Grants.java in the
// <PackageBase>.grants package. The class embeds the EntitlementGrant catalog
// from registry.json and resolves grant tokens — exact RPC grants
// (PKG_SERVICE_RPC) and wildcards (PKG_ANY, PKG_<CAP>_ANY) — to explicit
// exact-grant sets, mirroring the Go helper (emitGoGrantsHelper) and the
// language-agnostic reference in pkg/internal/common/verbs/entitlement.go.
//
// Wildcard grants carry a precomputed ExpandsTo list in the catalog, so the
// helper expands by table lookup rather than re-deriving from method metadata.
// The generated source depends only on the Java standard library (java.util.*)
// and is written to compile cleanly under -Xlint:all -Werror / failOnWarning.
func emitJavaGrantsHelper(cfg Config, grants []*spec.EntitlementGrantInfo) error {
	pkg := cfg.PackageBase + ".grants"

	// Stable order for deterministic output.
	sorted := append([]*spec.EntitlementGrantInfo(nil), grants...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].GetToken() < sorted[j].GetToken() })

	var entries strings.Builder
	for _, g := range sorted {
		entries.WriteString("        register(new Grant(")
		entries.WriteString(javaString(g.GetToken()))
		entries.WriteString(", ")
		entries.WriteString(javaString(g.GetPackage()))
		entries.WriteString(", ")
		entries.WriteString(javaString(g.GetServiceName()))
		entries.WriteString(", ")
		entries.WriteString(javaString(g.GetRpc()))
		entries.WriteString(", ")
		entries.WriteString(javaString(g.GetCapabilityScope()))
		entries.WriteString(", ")
		entries.WriteString(javaStringList(g.GetExpandsTo()))
		entries.WriteString(", ")
		entries.WriteString(javaStringList(g.GetRoutingAliasPackages()))
		entries.WriteString("));\n")
	}

	src := strings.ReplaceAll(javaGrantsTemplate, "{{PACKAGE}}", pkg)
	src = strings.ReplaceAll(src, "{{ENTRIES}}", entries.String())

	packagePath := filepath.FromSlash(strings.ReplaceAll(cfg.PackageBase, ".", "/"))
	dir := filepath.Join(cfg.OutputDir, "src", "main", "java", packagePath, "grants")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("failed to create grants dir: %w", err)
	}
	out := filepath.Join(dir, "Grants.java")
	if err := os.WriteFile(out, []byte(src), 0o644); err != nil {
		return fmt.Errorf("failed to write Grants.java: %w", err)
	}
	return nil
}

// javaString renders s as a Java string literal (reusing Go's quoting, which
// produces compatible escapes for the ASCII tokens in the catalog).
func javaString(s string) string {
	return strconv.Quote(s)
}

// javaStringList renders ts as a java.util.List<String> expression. An empty
// list becomes List.of() rather than null so ExpandsTo is never null.
func javaStringList(ts []string) string {
	if len(ts) == 0 {
		return "List.of()"
	}
	var b strings.Builder
	b.WriteString("List.of(")
	for i, t := range ts {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(javaString(t))
	}
	b.WriteString(")")
	return b.String()
}

const javaGrantsTemplate = `// Code generated by tacplus. DO NOT EDIT.
// Copyright (c) 2026 Second Star Cavalier LLC

package {{PACKAGE}};

import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.TreeSet;

/**
 * Grants is the generated entitlement-grant helper. It embeds the
 * EntitlementGrant catalog from registry.json and resolves grant tokens —
 * exact RPC grants (PKG_SERVICE_RPC) and wildcards (PKG_ANY, PKG_&lt;CAP&gt;_ANY) —
 * to explicit exact-grant sets. Runtime authorizers should normalize a grant
 * list once and authorize by intersection with a call's exact MethodGrant
 * token; wildcards are convenience input only and carry no runtime magic.
 */
public final class Grants {

    /** Grant describes one entitlement grant token. */
    public static final class Grant {
        /** The flattened upper-snake grant token. */
        public final String token;
        /** The proto package the grant belongs to. */
        public final String pkg;
        /** The RPC service name; empty for wildcard grants. */
        public final String service;
        /** The RPC name; empty for wildcard grants. */
        public final String rpc;
        /** The capability scope; empty for exact grants. */
        public final String capability;
        /** For wildcard grants: the exact tokens it implies; empty for exact grants. */
        public final List<String> expandsTo;
        /**
         * For exact grants whose (service, rpc) is also physically reachable
         * through a routing-alias package (e.g. an EventBus-hosted C2S publish
         * RPC declared in one proto package but dialed through "eventbus"): the
         * alias packages it is reachable under. Empty for grants with no alias
         * route, and for wildcard grants.
         */
        public final List<String> routingAliasPackages;

        public Grant(
                String token,
                String pkg,
                String service,
                String rpc,
                String capability,
                List<String> expandsTo,
                List<String> routingAliasPackages) {
            this.token = token;
            this.pkg = pkg;
            this.service = service;
            this.rpc = rpc;
            this.capability = capability;
            this.expandsTo = List.copyOf(expandsTo);
            this.routingAliasPackages = List.copyOf(routingAliasPackages);
        }

        /** Reports whether this grant is a package/capability wildcard. */
        public boolean isWildcard() {
            return !capability.isEmpty();
        }
    }

    private static final Map<String, Grant> BY_TOKEN = new LinkedHashMap<>();

    private static void register(Grant g) {
        BY_TOKEN.put(g.token, g);
    }

    static {
{{ENTRIES}}    }

	private Grants() {
	}

	/** Returns all generated grant tokens in stable catalog order. */
	public static List<String> tokens() {
		return List.copyOf(BY_TOKEN.keySet());
	}

	/** Returns the Grant for a token, or empty if it is not a known grant. */
	public static Optional<Grant> lookup(String token) {
		return Optional.ofNullable(BY_TOKEN.get(token));
	}

	/**
	 * Reports whether {@code token} authorizes service audience
	 * {@code targetPackage} — either because targetPackage is the grant's own
	 * entitlement-contract package, or because the grant's (service, rpc) is
	 * also physically routed through targetPackage as a routing alias (e.g. an
	 * EventBus-hosted C2S publish RPC declared in one proto package but dialed
	 * through "eventbus"). An unknown token authorizes nothing.
	 */
	public static boolean authorizesAudience(String token, String targetPackage) {
		Grant g = BY_TOKEN.get(token);
		if (g == null) {
			return false;
		}
		return g.pkg.equals(targetPackage) || g.routingAliasPackages.contains(targetPackage);
	}

    /** Reports whether token is a known package/capability wildcard grant. */
    public static boolean isWildcard(String token) {
        Grant g = BY_TOKEN.get(token);
        return g != null && g.isWildcard();
    }

    /**
     * Returns the exact RPC grant tokens a token implies: a wildcard expands to
     * its precomputed member tokens, a known exact token expands to itself, and
     * an unknown token expands to an empty list.
     */
    public static List<String> expand(String token) {
        Grant g = BY_TOKEN.get(token);
        if (g == null) {
            return List.of();
        }
        if (g.isWildcard()) {
            return List.copyOf(g.expandsTo);
        }
        return List.of(token);
    }

    /**
     * Expands every token to exact grants, removes duplicates, and returns a
     * stable sorted set — the form a runtime authorizer should compute once and
     * then authorize against by intersection.
     */
    public static List<String> normalize(List<String> tokens) {
        TreeSet<String> seen = new TreeSet<>();
        for (String t : tokens) {
            seen.addAll(expand(t));
        }
        return List.copyOf(seen);
    }

    /**
     * Returns the unknown input tokens that normalize would drop. Unknown grants
     * stay fail-closed, but scope/authorization paths should log these values
     * so grant vocabulary drift is visible.
     */
    public static List<String> unknownTokens(List<String> tokens) {
        TreeSet<String> unknown = new TreeSet<>();
        for (String token : tokens) {
            if (!BY_TOKEN.containsKey(token)) {
                unknown.add(token);
            }
        }
        return List.copyOf(unknown);
    }

    /**
     * Reports whether the normalized grants of candidate are a subset of those
     * of ceiling — i.e. ceiling grants everything candidate does.
     */
    public static boolean containsAll(List<String> candidate, List<String> ceiling) {
        TreeSet<String> cap = new TreeSet<>(normalize(ceiling));
        for (String g : normalize(candidate)) {
            if (!cap.contains(g)) {
                return false;
            }
        }
        return true;
    }

    /**
     * Returns the exact grant tokens a token implies, for operator/UI
     * "granting X grants these methods" surfaces.
     */
    public static List<String> explain(String token) {
        return expand(token);
    }
}
`
