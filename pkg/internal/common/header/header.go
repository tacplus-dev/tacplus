package header

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gitlab.com/seabeam/schematic/tacplus/pkg/internal/consts"
)

// LanguageCommentPrefix returns the comment prefix for a given language
func LanguageCommentPrefix(language string) string {
	switch language {
	case consts.LangGo, consts.LangRust, consts.LangJava, consts.LangTypeScript:
		return "//"
	case consts.LangPython:
		return "#"
	default:
		return "//" // default to C-style comments
	}
}

// formatHeaderLines formats header lines with a comment prefix
func formatHeaderLines(lines []string, prefix string) string {
	var sb strings.Builder
	for _, line := range lines {
		if line == "" {
			sb.WriteString(prefix + "\n")
		} else {
			sb.WriteString(prefix + " " + line + "\n")
		}
	}
	return sb.String()
}

// GeneratedHeader returns the standard generated code header for the specified language
// source is the optional source proto file path
func GeneratedHeader(language string, source string) string {
	prefix := LanguageCommentPrefix(language)
	return formatHeaderLines(consts.HeaderLinesWithSource(source), prefix) + "\n"
}

// SimpleHeader returns a simple header (just copyright + generated by) for the specified language
func SimpleHeader(language string) string {
	prefix := LanguageCommentPrefix(language)
	return formatHeaderLines(consts.BaseHeaderLines(), prefix) + "\n"
}

// ExampleHeader returns the header for generated example files
func ExampleHeader(language string, source string) string {
	prefix := LanguageCommentPrefix(language)
	return formatHeaderLines(consts.ExampleHeaderLines(source), prefix) + "\n"
}

// ReplaceProtocHeaders walks dir and replaces protoc-generated headers in all files
// matching ext (e.g. ".java", ".pb.go", "_pb2.py") with the standard tacplus header.
// packageKeyword is the language's package declaration keyword (e.g. "package" for Go/Java).
func ReplaceProtocHeaders(dir, language, ext, packageKeyword string) error {
	return filepath.Walk(dir, func(path string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() {
			return err
		}
		if !strings.HasSuffix(path, ext) {
			return nil
		}
		return replaceProtocHeader(path, language, packageKeyword)
	})
}

// ReplaceProtocHeader replaces the protoc-generated header in a single file.
func ReplaceProtocHeader(path, language, packageKeyword string) error {
	return replaceProtocHeader(path, language, packageKeyword)
}

func replaceProtocHeader(filePath, language, packageKeyword string) error {
	content, err := os.ReadFile(filePath)
	if err != nil {
		return err
	}

	lines := strings.Split(string(content), "\n")

	// Find the first non-comment, non-blank line (the package/code declaration)
	codeStart := -1
	prefix := LanguageCommentPrefix(language)
	for i, line := range lines {
		trimmed := strings.TrimSpace(line)
		if trimmed == "" || strings.HasPrefix(trimmed, prefix) {
			continue
		}
		// For languages with a package keyword, look for it specifically
		if packageKeyword != "" && strings.HasPrefix(trimmed, packageKeyword+" ") {
			codeStart = i
			break
		}
		// For languages without a package keyword (Python), first non-comment line is code
		if packageKeyword == "" {
			codeStart = i
			break
		}
	}
	if codeStart < 0 {
		return fmt.Errorf("no code declaration found in %s", filePath)
	}

	// Extract source from existing header if present
	source := ""
	for _, line := range lines[:codeStart] {
		if strings.Contains(line, "source:") || strings.Contains(line, "Source:") { // extract source path from existing generated header
			// Extract the source path from "// source: common/alpn.proto" or "// Source: common/alpn.proto"
			parts := strings.SplitN(line, ":", 2)
			if len(parts) == 2 {
				source = strings.TrimSpace(parts[1])
			}
			break
		}
	}

	var sb strings.Builder
	sb.WriteString(GeneratedHeader(language, source))
	sb.WriteString(strings.Join(lines[codeStart:], "\n"))
	return os.WriteFile(filePath, []byte(sb.String()), 0644)
}
