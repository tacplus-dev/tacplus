package registry

import (
	"fmt"
	"github.com/tacplus-dev/tacplus/pkg/internal/common/header"
	"github.com/tacplus-dev/tacplus/pkg/internal/consts"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	spec "github.com/tacplus-dev/tacplus/target/proto/spec/sys"
)

func init() { registerGrantsEmitter("typescript", emitTypeScriptGrantsHelper) }

// emitTypeScriptGrantsHelper writes <output>/grants/grants.ts. The module is a
// top-level generated module (like metaData.ts), so the root tsconfig's
// `include: ["**/*.ts"]` picks it up and type-checks it under strict mode with
// no extra packaging. Its behavior mirrors the Go reference helper
// (grants_emit.go) and the language-agnostic contract in
// pkg/internal/common/verbs/entitlement.go.
func emitTypeScriptGrantsHelper(cfg Config, grants []*spec.EntitlementGrantInfo) error {
	// Stable order for deterministic output.
	sorted := append([]*spec.EntitlementGrantInfo(nil), grants...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].GetToken() < sorted[j].GetToken() })

	var entries strings.Builder
	for _, g := range sorted {
		entries.WriteString("  ")
		entries.WriteString(tsQuote(g.GetToken()))
		entries.WriteString(": { token: ")
		entries.WriteString(tsQuote(g.GetToken()))
		entries.WriteString(", package: ")
		entries.WriteString(tsQuote(g.GetPackage()))
		if g.GetServiceName() != "" {
			entries.WriteString(", service: ")
			entries.WriteString(tsQuote(g.GetServiceName()))
		}
		if g.GetRpc() != "" {
			entries.WriteString(", rpc: ")
			entries.WriteString(tsQuote(g.GetRpc()))
		}
		if g.GetCapabilityScope() != "" {
			entries.WriteString(", capability: ")
			entries.WriteString(tsQuote(g.GetCapabilityScope()))
		}
		if exp := g.GetExpandsTo(); len(exp) > 0 {
			entries.WriteString(", expandsTo: [")
			for i, t := range exp {
				if i > 0 {
					entries.WriteString(", ")
				}
				entries.WriteString(tsQuote(t))
			}
			entries.WriteString("]")
		}
		entries.WriteString(" },\n")
	}

	src := header.Copyright(consts.LangTypeScript) + tsGrantsHeader + entries.String() + tsGrantsFooter

	dir := filepath.Join(cfg.OutputDir, "grants")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("failed to create grants dir: %w", err)
	}
	out := filepath.Join(dir, "grants.ts")
	if err := os.WriteFile(out, []byte(src), 0o644); err != nil {
		return fmt.Errorf("failed to write grants.ts: %w", err)
	}
	return nil
}

// tsQuote renders s as a double-quoted TypeScript string literal. Grant tokens,
// package/service/rpc names, and capability scopes are generated identifiers
// (upper-snake tokens and proto names) with no exotic characters, so Go's
// strconv.Quote produces a literal that is also a valid TS string literal.
func tsQuote(s string) string { return strconv.Quote(s) }

const tsGrantsHeader = `// Code generated by tacplus. DO NOT EDIT.
//
// The generated entitlement-grant helper. It embeds the EntitlementGrant
// catalog from registry.json and resolves grant tokens -- exact RPC grants
// (PKG_SERVICE_RPC) and wildcards (PKG_ANY, PKG_<CAP>_ANY) -- to explicit
// exact-grant sets. Runtime authorizers should normalize a grant list once and
// authorize by intersection with a call's exact MethodGrant token; wildcards
// are convenience input only and carry no runtime magic.

/** Grant describes one entitlement grant token. */
export interface Grant {
  /** The canonical grant token, e.g. "PKG_SERVICE_RPC" or "PKG_READ_ANY". */
  token: string;
  /** The proto package the grant belongs to. */
  package: string;
  /** The RPC service name; exact grants only. */
  service?: string;
  /** The RPC name; exact grants only. */
  rpc?: string;
  /** The capability scope; wildcard grants only ("" / absent for exact grants). */
  capability?: string;
  /** The exact tokens a wildcard implies; wildcard grants only. */
  expandsTo?: string[];
}

// The generated entitlement-grant catalog, keyed by grant token.
const byToken: Record<string, Grant> = {
`

const tsGrantsFooter = `};

/** Lookup returns the Grant for a token, or undefined if it is not a known grant. */
export function lookup(token: string): Grant | undefined {
  return byToken[token];
}

/** isWildcard reports whether token is a package/capability wildcard grant. */
export function isWildcard(token: string): boolean {
  const g = byToken[token];
  return g !== undefined && g.capability !== undefined && g.capability !== "";
}

/**
 * expand returns the exact RPC grant tokens a token implies: a wildcard expands
 * to its precomputed member tokens, a known exact token expands to itself, and
 * an unknown token expands to an empty array.
 */
export function expand(token: string): string[] {
  const g = byToken[token];
  if (g === undefined) {
    return [];
  }
  if (g.capability !== undefined && g.capability !== "") {
    return [...(g.expandsTo ?? [])];
  }
  return [token];
}

/**
 * normalize expands every token to exact grants, removes duplicates, and returns
 * a stable sorted set -- the form a runtime authorizer should compute once and
 * then authorize against by intersection.
 */
export function normalize(tokens: readonly string[]): string[] {
  const seen = new Set<string>();
  for (const t of tokens) {
    for (const e of expand(t)) {
      seen.add(e);
    }
  }
  return [...seen].sort();
}

/**
 * unknownTokens returns the unknown input tokens that normalize would drop.
 * Unknown grants stay fail-closed, but scope/authorization paths should log
 * these values so grant vocabulary drift is visible.
 */
export function unknownTokens(tokens: readonly string[]): string[] {
  const unknown = new Set<string>();
  for (const t of tokens) {
    if (byToken[t] === undefined) {
      unknown.add(t);
    }
  }
  return [...unknown].sort();
}

/**
 * containsAll reports whether the normalized grants of candidate are a subset of
 * those of ceiling -- i.e. ceiling grants everything candidate does.
 */
export function containsAll(candidate: readonly string[], ceiling: readonly string[]): boolean {
  const cap = new Set<string>(normalize(ceiling));
  for (const g of normalize(candidate)) {
    if (!cap.has(g)) {
      return false;
    }
  }
  return true;
}

/**
 * explain returns the exact grant tokens a token implies, for operator/UI
 * "granting X grants these methods" surfaces.
 */
export function explain(token: string): string[] {
  return expand(token);
}
`
