func TestHeaderLines_ContainsPublicSurfaceContract(t *testing.T) {
	lines := HeaderLines()
	foundTitle := false
	foundDoNotImport := false
	foundSM := false
	foundTacplusBug := false
	for _, l := range lines {
		switch {
		case l == "PUBLIC SURFACE CONTRACT:":
			foundTitle = true
		case strings.Contains(l, "Do not import or instantiate"):
			foundDoNotImport = true
		case strings.Contains(l, "generated Service Manager (SM)"):
			foundSM = true
		case strings.Contains(l, "tacplus bug"):
			foundTacplusBug = true
		}
	}
	if !foundTitle {
		t.Error("HeaderLines() does not contain the public surface contract title")
	}
	if !foundDoNotImport {
		t.Error("HeaderLines() does not warn against direct internal imports")
	}
	if !foundSM {
		t.Error("HeaderLines() does not direct consumers to the generated SM")
	}
	if !foundTacplusBug {
		t.Error("HeaderLines() does not tell consumers to report unreachable generated capabilities")
	}
}

func TestHeaderLines_ReturnsNewSliceEachCall(t *testing.T) {
	a := HeaderLines()
	b := HeaderLines()

	if len(a) != len(b) {
		t.Fatal("successive calls to HeaderLines() returned different lengths")
	}

	// Mutate the first slice and confirm the second is unaffected.
	original := a[0]
	a[0] = "MUTATED"
	if b[0] != original {
		t.Error("HeaderLines() returned the same underlying slice; mutations are shared")
	}
}

