	// PEM normalization + key/certificate validation (assert_enc_type).
	// Accepts raw PEM or base64-wrapped PEM (standard or URL-safe, padded or not).
	b.WriteString("    private static String normalizePemData(String value) {\n")
	b.WriteString("        if (value.contains(\"-----BEGIN\") && value.contains(\"-----END\")) {\n")
