// genvectors writes cross-test/fixtures/redact_vectors.json, the one fixture
// every leg of the redact gate (issue #274) checks its generated Redact<T> and
// sensitive-field validators against.
//
// The expected bytes are built by hand from the wire format, never by running a
// Redact<T>, so the fixture is an oracle independent of every leg. Fields are
// written in field-number order, as every protobuf runtime serializes them, and
// maps hold one entry each, so the serialized bytes are canonical.
//
//	go run ./cross-test/redact/genvectors > cross-test/fixtures/redact_vectors.json
package main

import (
	"encoding/hex"
	"encoding/json"
	"os"
	"strings"

	"google.golang.org/protobuf/encoding/protowire"
)

// Field numbers of cross-test/redact/proto/redact/redactcheck.proto, with the
// injected <field>_redacted indicators (50000 + the field's number) and trace_id.
const (
	traceID = 200
	ind     = 50000
)

const redacted = "REDACTED"

type wire []byte

func (w wire) str(num protowire.Number, s string) wire {
	w = protowire.AppendTag(w, num, protowire.BytesType)
	return protowire.AppendString(w, s)
}

func (w wire) byt(num protowire.Number, b []byte) wire {
	w = protowire.AppendTag(w, num, protowire.BytesType)
	return protowire.AppendBytes(w, b)
}

func (w wire) msg(num protowire.Number, m wire) wire { return w.byt(num, m) }

func (w wire) varint(num protowire.Number, v uint64) wire {
	w = protowire.AppendTag(w, num, protowire.VarintType)
	return protowire.AppendVarint(w, v)
}

func (w wire) flag(num protowire.Number) wire { return w.varint(num, 1) }

// entry is a map entry: key 1, value 2.
func entry(key string, value wire) wire { return wire(nil).str(1, key).byt(2, value) }

type redactCase struct {
	Name      string `json:"name"`
	Type      string `json:"type"`
	InputHex  string `json:"input_hex"`
	ExpectHex string `json:"expect_hex"`
}

type verdictCase struct {
	Name     string `json:"name"`
	Field    string `json:"field"`
	ValueHex string `json:"value_hex"`
	Expect   string `json:"expect"`
}

type fixture struct {
	Comment  []string      `json:"_comment"`
	Redact   []redactCase  `json:"redact"`
	Verdicts []verdictCase `json:"verdicts"`
}

func rc(name, typ string, in, want wire) redactCase {
	return redactCase{Name: name, Type: typ, InputHex: hex.EncodeToString(in), ExpectHex: hex.EncodeToString(want)}
}

func main() {
	f := fixture{Comment: []string{
		"Generated by go run ./cross-test/redact/genvectors; do not edit by hand.",
		"redact: input_hex through Redact<type>, serialized, must equal expect_hex byte for byte.",
		"verdicts: SecretCheck{token: \"Xk9#mP2$vL7@qR4!wT8&\", key: 0x00..0x1f, optional_token: \"\"} with field set to value_hex, through the generated validator.",
	}}

	// --- A uni-config with planted secrets everywhere a secret can hide. ---
	pkiIn := wire(nil).
		str(1, "-----BEGIN PRIVATE KEY-----\nMIIEvQIBADANBgkqhkiG9w0BAQEFAASC\n-----END PRIVATE KEY-----\n").
		byt(2, []byte{0x30, 0x82, 0x04, 0xbd, 0x02, 0x01}).
		str(3, "-----BEGIN CERTIFICATE-----\nMIIB\n-----END CERTIFICATE-----\n")
	pkiOut := wire(nil).str(1, redacted).byt(2, []byte(redacted)).str(3, redacted)

	secretsIn := wire(nil).
		str(1, "tok_live_9f8e7d6c5b4a39281706f5e4d3c2b1a0").
		byt(2, []byte{0xde, 0xad, 0xbe, 0xef, 0x01, 0x02, 0x03, 0x04}).
		str(3, "projects/acme/secrets/api-token/versions/7").
		varint(4, 1762214400).
		msg(5, pkiIn).
		str(6, "oauth-client-secret-1").
		str(6, "").
		str(7, "recovery-1234-5678")
	secretsOut := wire(nil).
		str(1, redacted).
		byt(2, []byte(redacted)).
		str(3, "projects/acme/secrets/api-token/versions/7"). // the version reference stays visible
		varint(4, 1762214400).
		msg(5, pkiOut).
		str(6, redacted).
		str(6, ""). // an empty element stays empty
		str(7, redacted).
		flag(ind + 1).flag(ind + 2).flag(ind + 5).flag(ind + 6).flag(ind + 7)

	endpointIn := func(url, pw string) wire {
		w := wire(nil).str(1, url)
		if pw != "" {
			w = w.str(2, pw)
		}
		return w
	}
	endpointOut := func(url string, hadPw bool) wire {
		w := wire(nil).str(1, url)
		if hadPw {
			w = w.str(2, redacted).flag(ind + 2)
		}
		return w
	}
	dbIn := wire(nil).str(1, "db.internal").str(2, "app").str(3, "db://app:hunter2@db.internal/app")
	dbOut := wire(nil).str(1, redacted).str(2, redacted).str(3, redacted)
	replicaIn := wire(nil).str(1, "replica.internal").str(2, "reader").str(3, "db://reader@replica.internal/app")

	uniIn := wire(nil).
		str(1, "acme-prod").
		msg(2, secretsIn).
		msg(3, endpointIn("https://api.example.com", "endpoint-password-1")).
		msg(3, endpointIn("https://status.example.com", "")).
		msg(4, entry("team", wire(nil).append("platform"))).
		msg(5, entry("east", endpointIn("https://east.example.com", "peer-password-east"))).
		varint(6, 3).
		msg(7, dbIn).
		msg(8, replicaIn).
		str(9, "api-token-one").
		str(9, "").
		msg(10, entry("jwt", wire([]byte{0x01, 0x02, 0x03, 0x04, 0x05}))).
		str(11, "page-2").
		str(traceID, "trace-4bf92f3577b34da6")
	uniOut := wire(nil).
		str(1, "acme-prod").
		msg(2, secretsOut).
		msg(3, endpointOut("https://api.example.com", true)).
		msg(3, endpointOut("https://status.example.com", false)).
		msg(4, entry("team", wire(nil).append("platform"))). // a plain map is untouched
		msg(5, entry("east", endpointOut("https://east.example.com", true))).
		varint(6, 3).
		msg(7, dbOut).
		msg(8, replicaIn). // the same type on a plain path keeps its values
		str(9, redacted).
		str(9, "").
		msg(10, entry("jwt", wire(redacted))). // map keys are identifiers: kept
		str(11, "page-2").
		str(traceID, "trace-4bf92f3577b34da6"). // the trace survives redaction
		flag(ind + 7).flag(ind + 9).flag(ind + 10)
	f.Redact = append(f.Redact, rc("uniconfig-planted-secrets", "UniConfig", uniIn, uniOut))

	// --- Empty and unset values stay empty, and set no indicator. ---
	emptySecretsIn := wire(nil).str(3, "v1").str(7, "") // recovery_code present but empty
	emptyIn := wire(nil).
		str(1, "acme-dev").
		msg(2, emptySecretsIn).
		msg(3, endpointIn("https://dev.example.com", "")).
		str(9, "").
		str(9, "")
	emptyOut := wire(nil).
		str(1, "acme-dev").
		msg(2, emptySecretsIn).
		msg(3, endpointOut("https://dev.example.com", false)).
		str(9, "").
		str(9, "")
	f.Redact = append(f.Redact, rc("uniconfig-empty-stays-empty", "UniConfig", emptyIn, emptyOut))
	f.Redact = append(f.Redact, rc("uniconfig-unset", "UniConfig", nil, nil))

	// --- Each type's own Redact<T>. ---
	f.Redact = append(f.Redact, rc("secrets-direct", "Secrets", secretsIn, secretsOut))
	f.Redact = append(f.Redact, rc("endpoint-password", "Endpoint",
		endpointIn("https://x.example.com", "pw"), endpointOut("https://x.example.com", true)))
	f.Redact = append(f.Redact, rc("endpoint-no-password", "Endpoint",
		endpointIn("https://x.example.com", ""), endpointOut("https://x.example.com", false)))
	// Non-ASCII and binary values become exactly the marker, whatever their length.
	f.Redact = append(f.Redact, rc("secretcheck-all-set", "SecretCheck",
		wire(nil).str(1, "ключ-секрет-✓").byt(2, []byte{0x00, 0xff, 0x00, 0xff}).str(3, "x"),
		wire(nil).str(1, redacted).byt(2, []byte(redacted)).str(3, redacted).flag(ind+1).flag(ind+2).flag(ind+3)))

	// --- Verdicts. ---
	v := func(name, field, value, expect string) {
		f.Verdicts = append(f.Verdicts, verdictCase{Name: name, Field: field, ValueHex: hex.EncodeToString([]byte(value)), Expect: expect})
	}
	vb := func(name string, value []byte, expect string) {
		f.Verdicts = append(f.Verdicts, verdictCase{Name: name, Field: "key", ValueHex: hex.EncodeToString(value), Expect: expect})
	}
	seq := func(n int) []byte {
		b := make([]byte, n)
		for i := range b {
			b[i] = byte(i)
		}
		return b
	}
	v("token-default-passes", "token", "Xk9#mP2$vL7@qR4!wT8&", "ok") // 20 x log2(95) = 131.4 bits
	v("token-required-empty", "token", "", "required")
	v("token-redacted-marker", "token", "REDACTED", "placeholder")
	v("token-redacted-lowercase", "token", "redacted", "placeholder")
	v("token-changeme", "token", "changeme", "placeholder")
	v("token-changeme-upper", "token", "CHANGEME", "placeholder")
	v("token-one-char-repeated", "token", strings.Repeat("a", 40), "placeholder")
	v("token-one-symbol-repeated", "token", strings.Repeat("#", 64), "placeholder")
	v("token-one-nonascii-repeated", "token", strings.Repeat("é", 30), "placeholder")
	v("token-10-lowercase", "token", "kqzvbnwmtx", "entropy")                        // 47 bits
	v("token-27-lowercase-below", "token", "qwertyuiopasdfghjklzxcvbnmq", "entropy") // 126.9 bits
	v("token-28-lowercase-passes", "token", "qwertyuiopasdfghjklzxcvbnmqw", "ok")    // 131.6 bits
	v("token-19-all-classes-below", "token", "Xk9#mP2$vL7@qR4!wT8", "entropy")       // 124.8 bits
	v("token-nonascii-counts-as-symbol", "token", "Xk9#mP2$vL7@qR4!wT8é", "ok")      // 20 code points, all classes
	v("token-22-digits-below", "token", "4815162342108314159265", "entropy")         // 73 bits
	vb("key-32-bytes-passes", seq(32), "ok")
	vb("key-16-bytes-at-floor", seq(16), "ok")
	vb("key-15-bytes-below", seq(15), "entropy")
	vb("key-required-empty", nil, "required")
	vb("key-redacted-bytes", []byte("REDACTED"), "placeholder")
	vb("key-zero-bytes", make([]byte, 32), "placeholder")
	v("optional-token-empty-passes", "optional_token", "", "ok") // not required
	v("optional-token-short", "optional_token", "short", "entropy")
	v("optional-token-changeme", "optional_token", "changeme", "placeholder")
	v("optional-token-at-64", "optional_token", "Ab1!Ab1!Ab", "ok") // 10 x log2(95) = 65.7 bits

	enc := json.NewEncoder(os.Stdout)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(f); err != nil {
		panic(err)
	}
}

func (w wire) append(s string) wire { return append(w, s...) }
