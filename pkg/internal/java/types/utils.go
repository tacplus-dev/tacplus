	b.WriteString("                return decoded;\n")
	b.WriteString("            }\n")
	b.WriteString("        } catch (IllegalArgumentException ignored) {}\n")
	b.WriteString("        return value;\n")
	b.WriteString("    }\n\n")
	b.WriteString("    private static String padBase64(String input) {\n")
	b.WriteString("        int pad = (4 - input.length() % 4) % 4;\n")
	b.WriteString("        return input + \"=\".repeat(pad);\n")
	b.WriteString("    }\n\n")
	b.WriteString("    public static void validateEncType(String value, String encType, String fieldName) throws ProtoException {\n")
	b.WriteString("        String pem = normalizePemData(value);\n")
	b.WriteString("        if (!pem.contains(\"-----BEGIN\") || !pem.contains(\"-----END\")) {\n")
